package ru.mars.network.local

import kotlinx.coroutines.flow.FlowCollector
import java.util.concurrent.atomic.AtomicLong

/**
 * Метка конфигурации прямого провайдера: адрес, ключ, модель.
 *
 * Зачем она нужна. Человек меняет адрес сервера (или модель) в настройках, пока шаг уже
 * идёт. Сокет, открытый на СТАРЫЙ адрес, жив, и его ответ приходит позже смены настройки.
 * Без метки такой ответ нельзя отличить от ответа по новому адресу: текст чужой модели
 * попадает в диалог, который человек уже начал вести с другой моделью, а вложения и
 * возможности модели считаются по чужому серверу.
 *
 * Как это ловится. Счётчик монотонно растёт при КАЖДОЙ смене профиля/URL/модели
 * ([bump]). Транспорт снимает метку в начале шага ([snapshot]) и сверяет её перед каждым
 * эмитом ([LocalProviderStamp.isOvertaken]). Расхождение означает: пока этот шаг шёл,
 * конфигурация стала другой, и его события больше не принадлежат текущему диалогу.
 *
 * Почему счётчик, а не сравнение URL. Сравнение по значению путает «вернул прежний
 * адрес» с «ничего не менял», а смена модели адрес вовсе не трогает. Монотонная метка
 * различает и это, и повторную смену на тот же адрес.
 *
 * Почему метка на процесс, а не на запрос. Метку поднимает тот, кто меняет настройки
 * (экран настроек), а сверяет транспорт — это разные места кода и, как правило, разные
 * нити. [AtomicLong] даёт видимость значения между ними без блокировок: читателей много,
 * писатель один и редкий.
 */
class LocalProviderSeq {

    private val counter = AtomicLong(0L)

    /** Текущая метка конфигурации; монотонно растёт, назад не идёт никогда. */
    fun readSeq(): Long = counter.get()

    /**
     * Метка, снятая в начале шага, больше не текущая: конфигурацию сменили.
     *
     * `true` — шаг устарел, его события эмитить нельзя.
     */
    fun isOvertaken(token: Long): Boolean = counter.get() != token

    /**
     * Отметить смену конфигурации: профиль, адрес, тип API или модель.
     *
     * Зовётся ДО того, как новый шаг начнёт снимать метку, иначе новый шаг получит
     * старую метку и умрёт на первом же эмите.
     *
     * @return новая метка.
     */
    fun bump(): Long = counter.incrementAndGet()

    /**
     * Снять метку для одного шага: `token` запоминается и больше не меняется.
     *
     * Снимать нужно в момент СОЗДАНИЯ потока, а не в момент подписки на него: между этими
     * двумя моментами настройки уже могли сменить, и тогда запрос ушёл бы по старому
     * профилю, а метка была бы новой — то есть шаг считался бы актуальным. Это и есть
     * fail-closed: сомнительный шаг молчит, а не пишет в чужой диалог.
     */
    fun snapshot(): LocalProviderStamp = LocalProviderStamp(this, counter.get())
}

/**
 * Метка одного шага: пара «счётчик + значение на момент старта».
 *
 * Отдельный тип, а не `Long` в кармане вызывающего, потому что метку нельзя перепутать
 * с номером попытки, индексом сообщения или `requestId`: у неё своя семантика и своя
 * проверка.
 */
class LocalProviderStamp internal constructor(
    private val seq: LocalProviderSeq,
    /** Значение счётчика на момент старта шага. */
    val token: Long,
) {

    /** Конфигурацию сменили после старта этого шага. */
    val isOvertaken: Boolean get() = seq.isOvertaken(token)
}

/**
 * Эмит события, если шаг ещё актуален.
 *
 * Единственная точка, через которую транспорт отдаёт события наружу: проверка «перед
 * каждым эмитом» иначе расползлась бы копиями по всем веткам (ошибка адреса, отказ по
 * вложению, кадр парсера, сбой сети), и одна забытая ветка вернула бы ровно тот дефект,
 * от которого эта метка и заведена.
 *
 * При устаревшей метке событие НЕ отправляется и функция возвращает `false` — вызывающий
 * обязан прекратить поток. `LocalChatEvent.Error` в этом случае не отправляется намеренно:
 * человек сам сменил адрес, это не сбой, и красная строка «сеть: ...» заставила бы его
 * искать несуществующую проблему.
 *
 * @return `true` — событие ушло; `false` — шаг устарел, эмиссии больше не будет.
 */
suspend fun FlowCollector<LocalChatEvent>.emitIfCurrent(
    stamp: LocalProviderStamp,
    event: LocalChatEvent,
): Boolean {
    if (stamp.isOvertaken) return false
    emit(event)
    return true
}
