package ru.mars.network.local

/**
 * Кэш возможностей модели: окно контекста, максимум ответа, reasoning, модальности.
 *
 * Зачем кэш вообще. Возможности приходят только из `GET /models` чужого сервера, а нужны
 * они в трёх местах и часто: пилюля контекста считает процент на каждом кадре, кнопка
 * «приложить фото» решает, можно ли отправлять картинку, переключатель reasoning — рисовать
 * ли себя. Ходить в сеть на каждый кадр нельзя, а держать каталог в профиле можно лишь
 * частично (там одно число — окно).
 *
 * Главное правило: **неизвестно ≠ нет**.
 *
 * `null` из [get] означает «не знаем» и НИКОГДА не означает «модель этого не умеет».
 * Разница не косметическая: «неизвестно» разрешает отправить картинку и показать
 * переключатель (провайдер сам откажет, если не умеет), а «нет» запрещает. Если путать
 * эти два состояния, то пустой ответ `/models` — обычное дело у посредников и на старте
 * приложения — навсегда запретил бы картинки и спрятал бы окно контекста у модели,
 * которая всё это умеет.
 *
 * Поэтому:
 * - пустой список моделей НЕ кэшируется как факт: запись для этого адреса удаляется,
 *   и [get] честно отвечает `null` («неизвестно»);
 * - модель, которой нет в каталоге, тоже даёт `null`, а не «не поддерживает»;
 * - кэш ничего не выдумывает: он отдаёт ровно те [LocalModelInfo], что разобрал
 *   [LocalModelCatalog] из ответа сервера.
 *
 * **Fail-closed при смене URL.** Ключ кэша обязан включать адрес провайдера: возможности —
 * свойство КОНКРЕТНОГО сервера, а не модели «вообще». После смены адреса старые данные
 * НЕ отдаются, иначе «модель принимает картинки» окажется правдой для чужого сервера, а
 * окно контекста — чужим числом, по которому пилюля нарисует неверный процент. Два
 * механизма закрывают это: адрес в ключе ([keyFor]) и полный сброс при любой смене
 * URL/ключа/типа API ([invalidate]).
 *
 * Потокобезопасность: вызовы идут с разных нитей (пилюля контекста, экран выбора модели,
 * разбор ответа на IO-диспетчере), поэтому все операции под одним монитором, а наружу
 * отдаются неизменяемые снимки. `ConcurrentHashMap` здесь не нужен: записей единицы,
 * а операции «прочитать и, если пусто, сходить в сеть» всё равно требуют одной блокировки
 * на уровне вызывающего — кэш не делает вид, что решает эту задачу за него.
 */
class LocalCapabilityCache {

    /** Один монитор на все операции: чтений много, записей мало, спор не о чем. */
    private val lock = Any()

    /** providerKey → (modelId → возможности). Внутренняя карта не меняется после записи. */
    private val byProvider = HashMap<String, Map<String, LocalModelInfo>>()

    /**
     * Возможности модели для конкретного адреса провайдера.
     *
     * @param providerKey ключ провайдера с адресом внутри — см. [keyFor].
     * @param modelId имя модели ровно в том виде, в каком оно уходит в поле `model`.
     * @return возможности модели; `null` — НЕИЗВЕСТНО (кэш пуст, сброшен, адрес другой
     *   или такой модели в каталоге не было). `null` не значит «не умеет».
     */
    fun get(providerKey: String, modelId: String): LocalModelInfo? {
        if (providerKey.isBlank() || modelId.isBlank()) return null
        return synchronized(lock) { byProvider[providerKey]?.get(modelId) }
    }

    /**
     * Запомнить разобранный каталог для конкретного адреса провайдера.
     *
     * Пустой список — не «возможностей нет», а «сервер не сказал»: запись для этого ключа
     * удаляется, чтобы прежние данные не выдавались за свежие. Элементы без имени модели
     * отбрасываются: по такому id никто не спросит, а место в карте он занимал бы.
     *
     * Вызов безопасен и на неизменном каталоге: повторная запись просто замещает снимок.
     */
    fun put(providerKey: String, models: List<LocalModelInfo>) {
        if (providerKey.isBlank()) return
        synchronized(lock) {
            if (models.isEmpty()) {
                byProvider.remove(providerKey)
                return
            }
            val index = LinkedHashMap<String, LocalModelInfo>(models.size)
            for (model in models) {
                if (model.id.isBlank()) continue
                index[model.id] = model
            }
            if (index.isEmpty()) {
                // Все элементы оказались без имени — это тоже «неизвестно», а не пустой каталог.
                byProvider.remove(providerKey)
                return
            }
            byProvider[providerKey] = index
        }
    }

    /**
     * Сброс всего кэша.
     *
     * Вызывается при ЛЮБОЙ смене URL, ключа или типа API — то есть везде, где поднимается
     * [LocalProviderSeq]. Точка отказа намеренно грубая: адрес в ключе уже защищает от
     * подмены сервера, но смена ключа может означать другую учётную запись того же шлюза,
     * а смена типа API — другой набор полей в ответе. Дешевле перезапросить каталог, чем
     * показать возможности, которых у текущей конфигурации нет.
     */
    fun invalidate() {
        synchronized(lock) { byProvider.clear() }
    }

    companion object {

        /**
         * Ключ провайдера для этого кэша: нормализованный базовый адрес.
         *
         * Почему адрес, а не `profile.id`: два профиля на один и тот же сервер имеют
         * одинаковые возможности, и различать их значило бы ходить в сеть дважды за одним
         * и тем же. Почему нормализованный: `https://host/v1` и `https://host/v1/` — один
         * сервер, и разный ключ для них давал бы промах кэша на ровном месте.
         *
         * Ключ API в ключ кэша НЕ входит и входить не должен: ключ — секрет, а ключ кэша
         * попадает в отладочные строки и дампы.
         */
        fun keyFor(profile: LocalProviderProfile): String =
            LocalProviderUrls.normalizeBaseUrl(profile.baseUrl)
    }
}
