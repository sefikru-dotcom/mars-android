package ru.mars.network.repository

/**
 * Порт ПЛАТНОГО облачного синтеза: текст + голос → готовое аудио или причина отказа.
 *
 * Зачем интерфейс, а не конкретный класс. Платных маршрутов у провайдера два, и они
 * НЕ равнозначны:
 * - асинхронный `POST /api/media/generate` + `GET /api/media/jobs/{id}`
 *   ([PlusVibeMediaTtsClient]) — рабочий контракт: задача ставится в очередь, аудио
 *   забирается по ссылке; синхронный запрос там может висеть до 32 с, но НЕ обрывает звук;
 * - синхронный `POST /v1/audio/speech` ([OpenAiSpeechTtsClient]) — быстрый старт, но
 *   дефектный: живой замер 3 из 10 вызовов вернул ОБРЕЗАННЫЙ фрагмент фразы
 *   (0,78–1,44 с вместо 5,6 с), причём одинаковые запросы давали то полный, то обрезанный
 *   ответ. Как единственный путь он не годится.
 *
 * Оба маршрута должны быть взаимозаменяемы для вызывающего слоя
 * ([RepositoryServerTtsClient]), поэтому здесь ровно один метод и один результат —
 * [ServerTtsResult]. Ни один из реализующих классов не бросает наружу: отказ провайдера —
 * это [ServerTtsResult.Unavailable], то есть приглашение к резерву, а не падение реплики.
 *
 * Значения по умолчанию подобраны так, чтобы вызов «текст + голос» работал одинаково:
 * - [model] пустая строка — «модель реализации по умолчанию» (у каждого маршрута своя);
 * - [instructions] `null` — «манера чтения реализации по умолчанию», а не «читать без
 *   манеры»: у `gpt-4o-mini-tts` без подсказки голос звучит ровно и безжизненно.
 */
interface PaidTtsClient {

    /**
     * Синтезирует [text] голосом [voice].
     *
     * @param text произносимый текст (уже очищенный от markdown вызывающим слоем).
     * @param voice имя голоса провайдера (`Alice`, `onyx`, …) — оно имеет смысл только
     *   внутри [model], поэтому оба параметра едут вместе.
     * @param model модель синтеза; пустая строка — модель реализации по умолчанию.
     * @param speed темп `0.25..4.0`; реализации зажимают значение, `NaN` — темп по умолчанию.
     * @param instructions манера чтения; `null` — манера реализации по умолчанию.
     * @param voiceId голос из БИБЛИОТЕКИ провайдера (`opts.voice_id`), а не именованный.
     *   `null` — обычный путь через [voice].
     *
     *   Зачем отдельный параметр, а не «положить id в [voice]». У ElevenLabs это ДВА разных
     *   поля контракта: `voice` — перечисление из 21 имени (Rachel, Alice, Lily, …), все они
     *   дефолтные англоязычные голоса; `voice_id` — свободная строка с id любого голоса из
     *   библиотеки, включая русские (Larisa, Kate). Если положить id в [voice], провайдер
     *   ответит `422` (значение вне enum) или молча подставит дефолт `Rachel` — и человек
     *   услышит не тот голос, не понимая почему.
     *
     *   Реализация, у которой такого поля нет (синхронный `/v1/audio/speech`), параметр
     *   ИГНОРИРУЕТ: притвориться, что отправила его, значило бы соврать о голосе.
     * @return [ServerTtsResult.Audio] с байтами либо [ServerTtsResult.Unavailable] с короткой
     *   причиной (`no_api_key`, `empty_text`, `text_too_long`, `transport`, `timeout`,
     *   `job_failed`, `http_<code>`, …). Текст реплики и ключ провайдера в причину не попадают.
     */
    suspend fun synthesize(
        text: String,
        voice: String,
        model: String = "",
        speed: Float = 1.0f,
        instructions: String? = null,
        voiceId: String? = null,
    ): ServerTtsResult
}
