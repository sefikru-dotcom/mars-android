        waitBudgetMs = LIBRARY_VOICE_WAIT_BUDGET_MS,
        natural = true,
        needsNetwork = true,
    )

    /**
     * Локальный резерв: piper `ru_RU-irina-medium`, TTFB ≈ 0.22 с, RTF 0.052.
     *
     * Почему именно irina: единственный проверенный piper-голос, который произносит
     * «Слэш» правильно без словаря (dmitri/denis/ruslan коверкают имя). Используется
     * ТОЛЬКО когда естественный голос недоступен (нет сети, движок выключен, 4xx по
     * голосу): это резерв, а не альтернатива. Право на попытку даёт фактический отказ
     * естественного профиля, а не догадка клиента; каталог сервера содержит
     * `ru_RU-irina-medium` (проверено живым синтезом, WAV ~157 КБ).
     */
    val LOCAL_IRINA: ServerTtsVoiceProfile = ServerTtsVoiceProfile(
        id = "local-irina",
        engine = "piper",
        voice = "ru_RU-irina-medium",
        rate = null,
        natural = false,
        needsNetwork = false,
    )

    /**
     * Политика голосового диалога: PlusVibe ElevenLabs (основной), Светлана, Дмитрий, Ава,
     * дешёвый PlusVibe gpt-4o-mini, два русских голоса из библиотеки ElevenLabs, локальный
     * резерв Ирина.
     *
     * `first()` — ОСНОВНОЙ голос приложения ([PLUSVIBE_ALICE]). Это осознанное решение
     * владельца: облачный синтез провайдера звучит живым разговорным тембром, а edge-голоса
     * остаются бесплатным резервом облака (и первым кандидатом, когда ключа провайдера нет).
     *
     * Восемь РАЗНЫХ голосов — требование владельца: раньше «Как в вебе», «Светлана» и
     * «Дмитрий» звучали одним системным голосом Android, потому что серверный синтез
     * падал (`429`/`401`) и движок молча уходил в фолбэк. Дубля «Как в вебе» больше нет:
     * `voiceId = null` подсвечивает основной голос ([DEFAULT_VOICE]).
     *
     * Порядок — это и есть политика: сначала основной платный голос, затем бесплатные
     * edge-голоса веба, затем остальные платные (дешёвый `gpt-4o-mini` и русские из
     * библиотеки ElevenLabs), последним — локальный резерв. Платные профили НИКОГДА не
     * участвуют в автоматическом понижении ([ru.mars.mobile.RepositoryServerTtsClient]
     * пропускает их в переборе): они стоят денег и выбираются человеком осознанно.
     */
    val VOICE_DIALOG: List<ServerTtsVoiceProfile> =
        listOf(
            PLUSVIBE_ALICE,
            NATURAL_SVETLANA,
            NATURAL_DMITRY,
            NATURAL_AVA,
            PLUSVIBE_ONYX,
            PLUSVIBE_LARISA,
            PLUSVIBE_KATE,
            LOCAL_IRINA,
        )

    /**
     * Голос по умолчанию — тот, что звучит, когда человек ничего не выбирал
     * (`voiceId == null`, «как в вебе»).
     *
     * Отдельная константа, а не `VOICE_DIALOG.first()`, потому что это ДВА разных решения:
     * порядок перебора (политика понижения) и выбор по умолчанию. Сегодня они совпадают,
     * но шторка подсвечивает именно [DEFAULT_VOICE], и правка одного не должна молча
     * менять другое.
     */
    val DEFAULT_VOICE: ServerTtsVoiceProfile get() = PLUSVIBE_ALICE

    /** Профиль по [id] или null (для настроек и миграции сохранённого выбора). */
    fun byId(id: String?): ServerTtsVoiceProfile? =
        VOICE_DIALOG.firstOrNull { it.id == id?.trim() }
}

/**
 * Один запрос синтеза: текст + профиль, уже разложенный на поля тела.
 *
 * Отдельный тип нужен транспорту ([ServerTtsTransport] в app-mobile): пять отдельных
 * аргументов (text, rate, pitch, engine, voice) слишком легко перепутать местами, а
 * ошибка здесь стоит неверного голоса или 400 от сервера.
 */
data class ServerTtsSpeechRequest(
    val text: String,
    val engine: String? = null,
    val voice: String? = null,
    val rate: String? = null,
    val pitch: String? = null,
) {

    companion object {

        /** Запрос по профилю; null-профиль — «пусть сервер выберет сам» (старое поведение). */
        fun of(text: String, profile: ServerTtsVoiceProfile?): ServerTtsSpeechRequest =
            ServerTtsSpeechRequest(
                text = text,
                engine = profile?.engine,
                voice = profile?.voice,
                rate = profile?.rate,
                pitch = profile?.pitch,
            )
    }
}
