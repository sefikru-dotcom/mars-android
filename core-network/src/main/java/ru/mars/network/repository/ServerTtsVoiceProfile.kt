package ru.mars.network.repository

/**
 * Голосовой профиль серверного синтеза: ЧТО просить у `POST /api/tts`.
 *
 * Зачем отдельный тип: «движок» и «голос» — это два поля запроса, которые должны ехать
 * вместе и не разъезжаться. Раньше Android слал только `{"text": …}`, и сервер подставлял
 * свой дефолт (`piper` + `ru_RU-dmitri-medium`) — то есть приложение говорило не тем
 * голосом, который выбран в вебе. Профиль фиксирует пару (engine, voice) + темп одним
 * значением, поэтому «естественный голос» — это явный объект, а не набор констант по
 * вызовам.
 *
 * [natural] — «желанный» голос (тот, что нравится в вебе: нейросеть Svetlana). Он ВСЕГДА
 * идёт первым в списке кандидатов; локальный piper — только резерв, а не замена.
 * [needsNetwork] — профиль требует сети (edge-tts). Локальный профиль работает и без неё.
 *
 * Контракт проверен живьём (см. `.mars/voice-upgrade/research/REPORT.md`):
 * `engine=edge, voice=ru-RU-SvetlanaNeural, rate=+8%` → `200 audio/mpeg`, TTFB ≈ 1.7 с;
 * `engine=piper, voice=ru_RU-irina-medium` → `200 audio/wav`, TTFB ≈ 0.22 с.
 */
data class ServerTtsVoiceProfile(
    /** Стабильный идентификатор профиля (для логов и настроек, не для сервера). */
    val id: String,
    /** Поле `engine` запроса: `edge`, `piper` или маршрут платного канала (`openai`, `plusvibe`). */
    val engine: String,
    /** Поле `voice` запроса: имя голоса движка. */
    val voice: String,
    /**
     * Модель платного облачного синтеза (`elevenlabs-v4-tts`, `gpt-4o-mini-tts`).
     *
     * Живёт в профиле, а не в клиенте, потому что модель и голос — такая же неразрывная
     * пара, как движок и голос у edge: голос `Alice` существует только внутри
     * `elevenlabs-v4-tts`, а `onyx` — только внутри `gpt-4o-mini-tts`. Один клиент на две
     * модели иначе пришлось бы выбирать голос «по имени» внутри себя, и однажды `Alice`
     * уехала бы в gpt-4o-mini с `400`.
     *
     * `null` — у профиля нет модели: серверные (`edge`/`piper`) её не знают вовсе.
     */
    val model: String? = null,
    /**
     * Голос из БИБЛИОТЕКИ провайдера (`opts.voice_id`) — свободная строка с id голоса
     * ElevenLabs, а не имя из перечисления 21 голоса.
     *
     * Зачем отдельное поле, если есть [voice]. Это ДВА разных поля контракта: [voice] —
     * enum (`Alice`, `Lily`, `Rachel`, …), все значения которого дефолтные англоязычные
     * голоса; `voice_id` — id любого голоса из библиотеки, включая русские (`Larisa`,
     * `Kate`). Русские голоса существуют ТОЛЬКО на этом пути: живая проверка профилей
     * библиотеки показала, что ни одно из 21 имени не верифицировано ElevenLabs в русском,
     * а `Alice` — британский голос (`language_code:"ru"` меняет фонетику, не тембр).
     *
     * `null` — обычный именованный голос ([voice]).
     *
     * Осторожно: путь `voice_id` на канале PlusVibe НЕСТАБИЛЕН и на 18.11.2026 не работал
     * вовсе — задача принималась (`202`, id подтверждён в `effectiveOpts`) и оставалась в
     * `processing` через 20–25 с без списания и без `failMsg` (5 из 5 попыток), тогда как
     * контрольный вызов с `voice:"Alice"` в ту же минуту дал аудио за 13,7 с. Поэтому такой
     * профиль обязан нести [waitBudgetMs]: иначе реплика молчит весь общий потолок (90 с).
     */
    val voiceId: String? = null,
    /**
     * Мягкий потолок ожидания ОДНОЙ реплики этим голосом, мс. `null` — общий потолок клиента.
     *
     * Зачем в профиле, а не в клиенте. Потолок клиента — транспортный (провайдер объявляет
     * 90 с, апстрим под нагрузкой отвечает 13 с), и он одинаков для всех голосов. Но у
     * библиотечного голоса дефект другой природы: задача не отвечает НИКОГДА, и ждать её
     * бессмысленно — тишина в 90 с неотличима от поломки. Здесь стоит срок, после которого
     * вызывающий слой ([ru.mars.mobile.RepositoryServerTtsClient]) перестаёт ждать и отдаёт
     * реплику нейро-резерву с объявленной подменой. Таймаут без фолбэка был бы потерей фразы;
     * таймаут с фолбэком — это и есть «не ждать зависший канал».
     */
    val waitBudgetMs: Long? = null,
    /** Поле `rate` (`+10%`) или null — темп движка по умолчанию. */
    val rate: String? = null,
    /** Поле `pitch` (`-5Hz`) или null — высота по умолчанию. */
    val pitch: String? = null,
    /** Желанный («естественный») голос: приоритет в выборе, не вытесняется резервом. */
    val natural: Boolean = false,
    /** Нужна сеть: локальный piper синтезирует на сервере и без выхода наружу. */
    val needsNetwork: Boolean = true,
) {

    /** Локальный (offline-способный) профиль — резерв, а не основной голос. */
    val isLocal: Boolean
        get() = !needsNetwork

    /**
     * Короткая подпись для логов: без текста и без секретов.
     *
     * Для библиотечного голоса печатается `voice_id`, а не имя: имя (`Larisa`) — это подпись
     * для человека, а в запрос уезжает именно id, и в логе должно быть видно то, что уехало.
     */
    val logTag: String
        get() = "$id($engine/${voiceId ?: voice})"
}

/**
 * Ключ кэша предсинтеза: ГОЛОС + текст, а не один текст.
 *
 * ## Почему пара, а не текст
 * Кэш предсинтеза ([ru.mars.mobile.ServerTtsSpeechEngine]) хранит уже синтезированное аудио
 * следующей фразы. Пока ключом был сам текст, смена голоса посреди ответа кэш не замечала:
 * остаток фраз доигрывал ПРЕЖНИМ голосом, хотя шторка уже показывала новый выбор. Человек
 * выбирал «Катю» и до конца реплики слышал «Ларису» — это ровно та жалоба «меняется
 * визуально, а по факту нет», из-за которой волна и затевалась.
 *
 * ## Почему профиль, а не имя голоса движка
 * Единица выбора человека — [ServerTtsVoiceProfile] (пара engine+voice+model). Два профиля
 * могут делить имя голоса, но различаться моделью (`Alice` живёт только внутри
 * `elevenlabs-v4-tts`), и отдавать аудио одного за другой нельзя.
 *
 * ## Почему управляющие символы
 * Разделитель `\u0000` и маркер «голос не выбран» `\u0001` взяты из управляющей зоны: id
 * профилей — обычные строки (`natural-dmitry`), такой символ в них не встречается, поэтому
 * простая склейка не даёт ложных совпадений (`of("a", "bc") != of("ab", "c")`). Хешировать
 * нечего: карта и так сравнивает строки, а читаемый ключ полезен в отладке.
 *
 * Класс чистый (никакого Android и состояния), поэтому проверяется JVM-тестом.
 */
object ServerTtsPrefetchKeys {

    /** Маркер «голос не выбран» («как в вебе»): отдельное значение, а не пустая строка. */
    private const val NO_VOICE: String = "\u0001"

    /** Граница пары. `\u0000` не может встретиться в id профиля. */
    private const val SEPARATOR: String = "\u0000"

    /**
     * Ключ кэша для фразы [text], синтезированной профилем [voiceId].
     *
     * `null` и пустой id означают одно и то же — «голос не выбран человеком»: пустой id не
     * отдельный голос, а отсутствие выбора.
     */
    fun of(voiceId: String?, text: String): String =
        (voiceId?.takeIf { it.isNotBlank() } ?: NO_VOICE) + SEPARATOR + text
}

