package ru.mars.mobile

/**
 * Версионирование асинхронных кадров рендера — чистая JVM-политика.
 *
 * Проблема: тяжёлый Markdown-парсинг стримящегося пузыря вынесен с главного потока;
 * результат публикуется позже. Если за время парсинга произошёл более новый рендер
 * (синхронная перерисовка, смена сессии, новый кадр), применять УСТАРЕВШИЙ кадр
 * поверх свежего нельзя — текст мигнёт назад. Gate выдаёт каждому фоновому кадру
 * монотонную версию и пропускает на UI только версии строго новее всего уже
 * применённого/инвалидированного.
 *
 * Контракт хоста (ChatActivity, все вызовы на main-потоке):
 * - [beginFrame] — перед запуском фонового парсинга;
 * - [canApply] — по готовности результата, перед публикацией на UI;
 * - [commit] — сразу после успешной публикации;
 * - [invalidateInFlight] — в любом синхронном renderMessages(): он рисует более
 *   свежее состояние, все незакоммиченные фоновые кадры устарели.
 */
class FrameVersionGate {
    private var issued = 0L
    private var committed = 0L

    /** Выдаёт версию нового асинхронного кадра (строго монотонно). */
    fun beginFrame(): Long = ++issued

    /** Можно ли опубликовать кадр [version]: только если он новее всего применённого. */
    fun canApply(version: Long): Boolean = version in (committed + 1)..issued

    /** Кадр опубликован на UI. */
    fun commit(version: Long) {
        if (version > committed) committed = version
    }

    /** Все выданные, но не опубликованные кадры устарели (прошёл синхронный рендер). */
    fun invalidateInFlight() {
        committed = issued
    }
}
