package ru.mars.mobile

/**
 * Язык перевода. Тег BCP-47 нужен промпту и синтезу.
 *
 * Три поля, а не одно, потому что язык участвует в трёх разных местах и в каждом нужен
 * свой вид:
 * - [code] — то, что понимает промпт и голосовой канал (`ru`, `en`); это не текст для
 *   человека и в интерфейсе не показывается;
 * - [label] — как называть язык в русском интерфейсе («Немецкий»), чтобы список читался
 *   одним алфавитом и не заставлял искать строку в чужой графике;
 * - [nativeLabel] — как язык называет себя («Deutsch»). Нужен в двух случаях: человек ищет
 *   свой язык глазами по родному написанию, а распознавание речи и синтез на части движков
 *   подбирают голос/локаль по самоназванию языка.
 *
 * Поля не выводятся друг из друга: «Türkçe» из «Турецкий» не получается, а код `de`
 * не говорит, какое из двух написаний показывать.
 */
data class TranslateLanguage(
    val code: String,
    val label: String,
    val nativeLabel: String,
)

/**
 * Направление перевода: с какого языка на какой.
 *
 * Направление — самостоятельная величина, а не пара аргументов, потому что его целиком
 * передают через границы: экран выбора отдаёт его наружу, промпт и подсказка строятся из
 * него, а «поменять местами» — это операция над направлением, а не над двумя строками,
 * которые легко перепутать местами в вызове.
 */
data class TranslateDirection(
    val from: TranslateLanguage,
    val to: TranslateLanguage,
) {
    /**
     * Перевод «с русского на русский».
     *
     * Вынесено в свойство, потому что это единственное вырожденное состояние режима, и
     * проверять его приходится в трёх местах сразу: промпт не собирается, подсказка
     * объясняет, почему, а кнопка подтверждения гаснет. Сравнение по коду, а не по
     * объекту: языки приходят из разных мест (список, настройки, сохранённое состояние
     * экрана) и могут быть разными экземплярами одного языка.
     */
    val isSame: Boolean get() = from.code == to.code
}

/**
 * Правила режима перевода: какие языки предлагать, что отправить модели и когда её ответ
 * считать переводом, а не отказом.
 *
 * Ни одного импорта `android.*` — по той же причине, что и в [LocalContinuePolicy]:
 * всё, что здесь есть, это данные и сравнение строк, поэтому правила проверяются
 * JVM-тестом без эмулятора, а экран ([TranslateSheet]) остаётся тонким и только рисует
 * список по [LANGUAGES] и подсказку по [pendingHint].
 *
 * Почему перевод — это промпт, а не новая технология: каскад «распознавание → модель →
 * синтез» в проекте уже работает, и режим перевода отличается от обычного разговора
 * ровно двумя вещами — инструкцией модели и тем, что ответ читается вслух. Поэтому здесь
 * нет ни микрофона, ни синтеза: политика не имеет права открывать голосовой канал,
 * который принадлежит `LocalVoiceController` (второй захват даёт «микрофон занят»).
 *
 * Главное ограничение всего файла — ответ читают вслух. Всё, что в обычном чате было бы
 * безобидной разметкой (заголовок, список, звёздочки выделения, обратные кавычки), в
 * наушниках произносится как мусор, а вступление «Вот перевод:» съедает первую секунду
 * реплики. Отсюда и жёсткая формулировка [systemPrompt], и проверка [looksLikeTranslation].
 */
object TranslatePolicy {

    /** Заголовок листа и режима. */
    const val TITLE: String = "Перевод"

    /**
     * Список языков для выбора. Первые два — русский и английский.
     *
     * Порядок не алфавитный, а по частоте: русский и английский — это почти весь режим,
     * и они должны стоять первыми, чтобы обычный случай решался без поиска. Остальные
     * языки добавлены те, на которых проект реально используется; список намеренно
     * короткий — длинный список языков в пилюлях превращается в свалку, а не в выбор.
     */
    val LANGUAGES: List<TranslateLanguage> = listOf(
        TranslateLanguage("ru", "Русский", "Русский"),
        TranslateLanguage("en", "Английский", "English"),
        TranslateLanguage("de", "Немецкий", "Deutsch"),
        TranslateLanguage("tr", "Турецкий", "Türkçe"),
    )

    /**
     * Направление по умолчанию: с русского на английский.
     *
     * Именно так, а не наоборот: человек, которому нужен перевод, чаще говорит на своём
     * языке и хочет услышать чужой. Обратное направление — один тап по «Поменять», и это
     * осознанное действие, а не состояние по умолчанию.
     */
    fun defaultDirection(): TranslateDirection = TranslateDirection(LANGUAGES[0], LANGUAGES[1])

    /**
     * Переставить направление местами — главный жест в этом режиме.
     *
     * Отдельная операция, а не два присваивания на экране: перестановка обязана быть
     * обратимой (два вызова дают исходное направление), и это свойство проще удержать,
     * когда местами меняются ровно два поля одного типа. Языки не копируются и не
     * пересобираются: направление остаётся тем же набором языков, меняется только роль.
     */
    fun swap(direction: TranslateDirection): TranslateDirection =
        TranslateDirection(from = direction.to, to = direction.from)

    /**
     * Системный промпт перевода.
     *
     * Требования, без которых результат бесполезен в голосовом режиме: только перевод,
     * без пояснений и кавычек, без транслитерации, без markdown — ответ читается вслух.
     * Каждый пункт ниже появился из конкретного дефекта:
     * - пояснения и вступления («Вот перевод», «Это значит») — самые частые спутники
     *   перевода у моделей, и в наушниках они звучат как часть перевода;
     * - кавычки вокруг ответа модель ставит «для аккуратности», а синтез читает их как
     *   паузу в неожиданном месте;
     * - транслитерация («privet») вместо перевода — типичный обход, когда модель не
     *   уверена в слове; для слушателя это не перевод;
     * - markdown (звёздочки, решётки, обратные кавычки) синтез произносит словами
     *   «звёздочка», «решётка»;
     * - просьба не переспрашивать важна потому, что в голосовом режиме уточняющий вопрос
     *   модели человек услышит уже после того, как договорил, и не поймёт, что от него
     *   хотят.
     *
     * При [TranslateDirection.isSame] промпт **не собирается**: возвращается пустая строка.
     * Это не текст-отказ, а именно отсутствие промпта — отказ, отправленный модели как
     * инструкция, был бы исполнен как просьба («не переводи») и дал бы ответ, который
     * потом читают вслух. Пустую строку вызывающий обязан отличить от промпта
     * (`isBlank`), а если ему нужно различие в типе — есть [promptOrNull].
     */
    fun systemPrompt(direction: TranslateDirection): String {
        if (direction.isSame) return ""
        val from = describe(direction.from)
        val to = describe(direction.to)
        return buildString(512) {
            append("Ты — переводчик в голосовом режиме. Переведи реплику с языка ")
            append(from)
            append(" на язык ")
            append(to)
            append(".\n")
            append("Ответ читают вслух, поэтому верни только готовый перевод: без пояснений, ")
            append("без вступления, без кавычек и без подписи.\n")
            append("Никакой разметки: ни заголовков, ни списков, ни звёздочек, ни обратных ")
            append("кавычек, ни таблиц — только обычный текст.\n")
            append("Не транслитерируй и не оставляй слов исходного языка, если у них есть ")
            append("перевод. Имена, числа и названия оставляй как есть.\n")
            append("Если реплика неполная или с оговоркой, переведи так, как понял, и не переспрашивай.")
        }
    }

    /**
     * То же, что [systemPrompt], но вырожденное направление даёт `null`.
     *
     * Дублирует [systemPrompt] намеренно: `String` из контракта не умеет отличать «промпта
     * нет» от «промпт пустой», а вызывающему (координатору, который подключит экран к
     * голосовому каналу) удобнее проверять `null`, чем помнить про `isBlank`. Обе функции
     * считаются в одном месте, поэтому разъехаться не могут.
     */
    fun promptOrNull(direction: TranslateDirection): String? =
        if (direction.isSame) null else systemPrompt(direction)

    /**
     * Проверка, что ответ модели похож на перевод, а не на отказ или лекцию.
     *
     * Зачем вообще проверять: промпт — просьба, а не гарантия. Модель без доступа к
     * сети, модель с фильтром или модель, которой «не хватило» одного языка, отвечает
     * вежливым отказом; если такой ответ прочитать вслух как перевод, человек услышит
     * «Извините, я не могу» вместо своей фразы и решит, что сломался перевод.
     *
     * Что считается «не переводом»:
     * - пустое или состоящее из одной пунктуации (перевода нет);
     * - блок кода или markdown-выделение: промпт их запрещает, значит модель не выполнила
     *   инструкцию и её текст нельзя читать вслух как есть;
     * - отказ, собранный из двух частей: вежливое начало **и** глагол неспособности
     *   ([REFUSAL_VERBS]). Именно пара, а не любое слово по отдельности: перевод фразы
     *   «Извините, я опоздал» начинается с того же «извините», а перевод «Я не могу
     *   прийти» — с того же «не могу», и отбраковать их значило бы не озвучить нормальный
     *   перевод отрицательного предложения. Отказ же всегда соединяет оба: человеку
     *   извиняются **и** сообщают, что перевести не могут;
     * - фразы, которые в переводе не встречаются вовсе ([REFUSAL_PHRASES]:
     *   «не могу перевести», «as an ai», «нет доступа»), и встречные вопросы
     *   ([REFUSAL_QUESTIONS]: «уточните», «какой язык»).
     *
     * Проверяется только начало ответа ([REFUSAL_WINDOW] символов): отказ всегда стоит
     * первым, а поиск по всему тексту ловил бы слово «извините» внутри длинного перевода.
     */
    fun looksLikeTranslation(answer: String): Boolean {
        val trimmed = answer.trim()
        if (trimmed.isEmpty()) return false
        // Одна пунктуация или одни эмодзи — перевода в ответе нет.
        if (trimmed.none { it.isLetterOrDigit() }) return false
        // Разметка, которую промпт прямо запретил: значит ответ не по инструкции.
        if (MARKDOWN_MARKS.any { trimmed.contains(it) }) return false
        val head = trimmed.lowercase().take(REFUSAL_WINDOW)
        if (REFUSAL_PHRASES.any { head.contains(it) }) return false
        if (REFUSAL_QUESTIONS.any { head.contains(it) }) return false
        val apologetic = POLITE_OPENERS.any { head.startsWith(it) }
        return !(apologetic && REFUSAL_VERBS.any { head.contains(it) })
    }

    /**
     * Заготовка реплики человека: что показывать, пока перевода нет.
     *
     * Подсказка описывает именно действие в этом режиме, а не состояние загрузки: человек
     * уже нажал «Перевод» и должен понять, что теперь можно просто говорить, а не искать
     * кнопку. Направление названо словами, а не стрелкой с кодами: «Русский → Английский»
     * читается быстрее, чем `ru → en`, и не требует знания тегов.
     *
     * Вырожденное направление объясняется, а не замалчивается: экран, у которого язык
     * оказался одинаковым с двух сторон, обязан сказать, что переводить нечего, иначе
     * человек будет говорить в пустоту и ждать ответа.
     */
    fun pendingHint(direction: TranslateDirection): String =
        if (direction.isSame) {
            "Выберите два разных языка: переводить «${direction.from.label}» на «${direction.from.label}» нечего."
        } else {
            "${direction.from.label} → ${direction.to.label}. Говорите — перевод появится здесь."
        }

    /**
     * Подпись направления для заголовка и ленты: «Русский → Английский».
     *
     * Одна функция на все места, где направление называют человеку: подпись в шапке листа,
     * строка в ленте и уведомление должны совпадать дословно, иначе человек видит «RU-EN»
     * в одном месте и «Английский» в другом и не уверен, тот ли это режим.
     */
    fun directionLabel(direction: TranslateDirection): String =
        "${direction.from.label} → ${direction.to.label}"

    /**
     * Язык по тегу BCP-47 (`ru`, `EN`, ` en `).
     *
     * Тег приходит из трёх источников — настройки, распознавание речи, сохранённое
     * состояние экрана — и в каждом он может быть в другом регистре и с пробелом по краям.
     * Неизвестный тег даёт `null`, а не «русский по умолчанию»: подставить чужой язык
     * значит молча переводить не туда, и человек узнает об этом только по результату.
     */
    fun byCode(code: String?): TranslateLanguage? {
        val key = code?.trim()?.lowercase()
        if (key.isNullOrEmpty()) return null
        return LANGUAGES.firstOrNull { it.code == key }
    }

    /**
     * Языки, на которые можно переводить с [from]: все, кроме него самого.
     *
     * Вырожденное направление отсекается здесь, на уровне данных, а не только в
     * интерфейсе: лист гасит недоступные пилюли по этому списку, и если однажды появится
     * второй вход в режим перевода, запрет уже будет частью политики, а не свойством
     * одного экрана.
     */
    fun availableTargets(from: TranslateLanguage): List<TranslateLanguage> =
        LANGUAGES.filter { it.code != from.code }

    /** Сколько символов ответа проверять на отказ: отказ всегда стоит в начале. */
    private const val REFUSAL_WINDOW = 120

    /** Разметка, которую промпт запретил: её присутствие выдаёт ответ не по инструкции. */
    private val MARKDOWN_MARKS = listOf("**", "```", "##", "| ---")

    /**
     * Обороты отказа, которые в переводе не встречаются вовсе.
     *
     * Здесь только то, что говорит модель о собственной неспособности или о себе: «не могу
     * перевести», «нет доступа», «языковая модель». Голое «не могу» сюда не входит — это
     * ещё и нормальный перевод отрицательного предложения («Я не могу прийти»).
     */
    private val REFUSAL_PHRASES = listOf(
        "не могу перевести",
        "не могу помочь",
        "не могу ответить",
        "не могу выполнить",
        "не могу этого сделать",
        "не имею доступа",
        "нет доступа к этой",
        "языковая модель",
        "я не человек",
        "cannot translate",
        "can't translate",
        "can not translate",
        "unable to translate",
        "cannot help",
        "can't help",
        "cannot assist",
        "can't assist",
        "not able to translate",
        "as an ai",
    )

    /**
     * Встречный вопрос вместо перевода: моделям не хватило направления.
     *
     * Отдельно от [REFUSAL_PHRASES], потому что это не извинение, а требование уточнить —
     * для голосового режима одинаково бесполезное (человек уже договорил и ждёт перевода).
     */
    private val REFUSAL_QUESTIONS = listOf(
        "уточните",
        "какой язык",
        "какие языки",
        "не указан",
        "не указано",
    )

    /**
     * Вежливое начало ответа. Само по себе ничего не значит: с него начинается и отказ, и
     * нормальный перевод фразы «Извините, я опоздал».
     *
     * Сравнение по основам («извин»), а не по формам: «Извините», «Извиняюсь» и «Приношу
     * извинения» — одно и то же начало, и перечислять все формы бессмысленно.
     */
    private val POLITE_OPENERS = listOf(
        "извин",
        "прошу прощения",
        "приношу извинения",
        "к сожалению",
        "sorry",
        "i'm sorry",
        "i am sorry",
    )

    /**
     * Глагол неспособности. Вместе с [POLITE_OPENERS] даёт отказ, по отдельности — обычную
     * отрицательную фразу, поэтому проверяется только в паре с вежливым началом.
     */
    private val REFUSAL_VERBS = listOf(
        "не могу",
        "не получится",
        "не удалось",
        "не в состоянии",
        "cannot",
        "can't",
        "can not",
        "unable",
        "not able",
    )

    /**
     * Язык для промпта: название, самоназвание и тег — «Английский» (English, en).
     *
     * Три вида в одной скобке, потому что модель узнаёт язык по любому из них, а человек
     * (в отладке промпта) видит сразу, что подставилось. Самоназвание не дублируется,
     * когда совпадает с названием: «Русский» (Русский, ru) выглядит как опечатка.
     */
    private fun describe(language: TranslateLanguage): String =
        if (language.nativeLabel == language.label) {
            "«${language.label}» (${language.code})"
        } else {
            "«${language.label}» (${language.nativeLabel}, ${language.code})"
        }
}