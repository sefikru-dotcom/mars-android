package ru.mars.mobile

/**
 * Вкладка экрана «Музыка»: чарт, волна, лента «Для тебя», избранное, очередь, серверные
 * плейлисты, серверная история.
 *
 * Верхнеуровневый тип в своём файле, а не вложенный в [MusicActivity]: секции-расширения
 * (`MusicShellSection`, `MusicPlayerBarSection`, …) ссылаются на него из других файлов, а
 * вложенный классификатор через receiver extension-функции не виден — резолвятся только
 * члены. План (§4.3, шаг 13) предполагал оставить его вложенным с `internal`; это
 * единственная правка переноса, сделанная иначе, и без неё модуль не компилируется.
 */
internal enum class MusicTab { CHART, FLOW, FOR_YOU, FAVORITES, QUEUE, PLAYLISTS, HISTORY }
