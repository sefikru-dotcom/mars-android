package ru.mars.mobile

/**
 * Мьютекс смены модели: применяется только ПОСЛЕДНИЙ запрос (last-one-wins).
 *
 * Дефект, который здесь закрывается: человек открывает пикер и быстро выбирает модель
 * дважды — `A`, потом `B`. Выбор `B` уходит на сервер и возвращается первым, `A` —
 * вторым (медленный ответ, ретрай, смена адреса). Без метки поздний ответ `A`
 * перезаписывает экран и профиль, и в чате оказывается модель, которую человек
 * не выбирал последней. Снаружи это выглядит как «нажал B, отвечает A».
 *
 * Почему чистая функция, а не `Mutex`/`withLock`: задача не в том, чтобы выполнять
 * выбор строго по очереди (это как раз замедлило бы отклик на нажатие), а в том, чтобы
 * отбросить устаревший РЕЗУЛЬТАТ. Поэтому нужна монотонная метка запроса и сравнение
 * с последней выданной: `shouldApply(requestSeq, latestSeq)` — правда только для той
 * метки, которую выдали последней. Первый ответ при этом не блокирует второй —
 * он просто проигрывает по метке.
 *
 * Экран пикера здесь не меняется: подключение — зона координатора (§4 контракта
 * волны 12). Файл обязан компилироваться и проверяться JVM-тестом.
 */
internal object LocalModelPickPolicy {

    /**
     * Чей результат применять.
     *
     * `true` — только если [requestSeq] совпадает с последней выданной меткой
     * [latestSeq]. Нулевая метка — «запрос не выдавался»: такой результат не применяется
     * никогда, иначе применение по умолчанию прошло бы до первого `begin()`.
     *
     * Сравнение на равенство, а не `>=`: метка, выданная ПОЗЖЕ последней (невозможно
     * при честном счётчике, но возможно после сброса процесса), тоже устарела —
     * применять её значит показать модель, которую человек уже не выбирал.
     */
    fun shouldApply(requestSeq: Long, latestSeq: Long): Boolean =
        requestSeq > 0L && requestSeq == latestSeq

    /**
     * Следующая метка запроса.
     *
     * Монотонно растёт на единицу от текущей. Неположительная метка (начало, сброс,
     * битое сохранённое значение) и переполнение `Long.MAX_VALUE` начинают счёт заново
     * с `1`: метка обязана остаться положительной, иначе [shouldApply] перестал бы
     * применять что-либо вообще.
     */
    fun nextSeq(current: Long): Long =
        if (current <= 0L || current == Long.MAX_VALUE) 1L else current + 1L
}

/**
 * Готовая к подключению гонка выдачи меток для экрана пикера.
 *
 * Почему отдельный класс, а не поле в Activity: метку выдают с UI-нити, а применяют
 * результат — с нити ответа; два быстрых нажатия могут пересечься. Счётчик под замком
 * гарантирует, что две выдачи не получат одну метку (иначе оба ответа считались бы
 * последними и оба применились).
 *
 * Порядок использования на экране: `val seq = gate.begin()` перед запросом каталога,
 * затем в обработчике ответа `if (gate.shouldApply(seq)) { …применить… }`.
 */
internal class LocalModelPickGate {

    private val lock = Any()

    /** Последняя выданная метка; `0` — меток ещё не выдавали. */
    private var latest = 0L

    /** Выдать метку нового запроса; она же становится последней. */
    fun begin(): Long = synchronized(lock) {
        latest = LocalModelPickPolicy.nextSeq(latest)
        latest
    }

    /** Применять ли результат запроса с меткой [requestSeq]. */
    fun shouldApply(requestSeq: Long): Boolean = synchronized(lock) {
        LocalModelPickPolicy.shouldApply(requestSeq, latest)
    }

    /** Последняя выданная метка — для диагностики и тестов. */
    val latestSeq: Long get() = synchronized(lock) { latest }

    /** Сброс: следующий [begin] снова начнёт с `1`. */
    fun reset() {
        synchronized(lock) { latest = 0L }
    }
}
