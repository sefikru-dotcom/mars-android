package ru.mars.mobile

/**
 * Показывать ли живой транскрипт ASR прямо в композере, не затирая то, что человек набрал руками.
 *
 * ## Зачем отдельная политика
 * `VoiceDialogLoop.onPartialTranscript` приходит на каждое уточнение движка (несколько раз в
 * секунду). Писать этот текст в поле ввода «как есть» нельзя: человек мог начать печатать ответ
 * сам, и первое же уточнение стёрло бы его правку — молча, без возможности отменить. Но и
 * полностью отказываться от предпросмотра нельзя: без него непонятно, слышит ли Марс вообще
 * (особенно в шумном месте), и человек говорит в пустоту.
 *
 * Правило поэтому узкое и проверяемое:
 * - поле пустое → показываем partial (это наш текст, терять нечего);
 * - в поле ровно тот текст, который мы сами записали прошлым partial → заменяем (это
 *   продолжение той же расшифровки);
 * - в поле что-то другое → НЕ трогаем: чужая правка важнее предпросмотра.
 *
 * Финал (`onFinal`) снимает «нашу» метку: после отправки реплики поле снова ничьё, и следующий
 * partial начинает с чистого листа. Сброс — на выключение режима, чтобы метка не переехала в
 * новый диалог.
 *
 * Класс чистый и однопоточный: его зовёт только хост с главного потока.
 */
class VoicePartialPreviewPolicy {

    /** Что делать с partial. */
    sealed interface Decision {
        /** Записать [text] в композер (заменяя прежний предпросмотр). */
        data class Apply(val text: String) : Decision

        /** Оставить поле как есть — там текст человека. */
        data object Keep : Decision
    }

    /** Текст, который политика сама записала в композер последним; `null` — ничего не писали. */
    var lastApplied: String? = null
        private set

    /**
     * Решение по очередному partial.
     *
     * @param partial расшифровка движка (может быть пустой/пробельной — тогда показывать нечего).
     * @param composerText текущее содержимое поля ввода.
     */
    fun onPartial(partial: String, composerText: String): Decision {
        val clean = partial.trim()
        if (clean.isEmpty()) return Decision.Keep
        val current = composerText.trim()
        val mine = lastApplied
        val allowed = current.isEmpty() || (mine != null && current == mine.trim())
        if (!allowed) return Decision.Keep
        lastApplied = clean
        return Decision.Apply(clean)
    }

    /**
     * Реплика распознана целиком: предпросмотр больше не «наш».
     *
     * Метку снимаем, но текст в поле не трогаем — его отправит обычный путь хода (или человек
     * отредактирует).
     */
    fun onFinal() {
        lastApplied = null
    }

    /** Режим выключен/сменился диалог: следующая реплика начинается с чистого листа. */
    fun reset() {
        lastApplied = null
    }
}
