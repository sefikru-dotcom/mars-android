package ru.mars.mobile

import ru.mars.network.local.LocalTurnMetrics

/**
 * Политика «Продолжить обрезанный ответ» — когда предлагать продолжение и что дописать
 * в историю, чтобы модель продолжила, а не начала заново.
 *
 * Ни одного импорта `android.*`: решение о кнопке и текст служебной реплики — это данные
 * и арифметика над флагами, а не разметка. Поэтому политика проверяется JVM-тестом
 * (`LocalContinuePolicyTest`) без эмулятора, а экран ([LocalChatActivity]) остаётся
 * тонким: он только рисует кнопку по [shouldOffer] и подставляет [CONTINUE_PROMPT]
 * в историю.
 *
 * Почему продолжение вообще нужно отдельным правилом: локальный провайдер обрезает ответ
 * по `max_tokens` молча — текст заканчивается на середине фразы, и человек видит
 * «готовый» ответ, который на деле недописан. Дописать его можно только новым запросом,
 * потому что лимит уже исчерпан. Отсюда два независимых вопроса, которые политика
 * разделяет намеренно:
 *
 * 1. [shouldOffer] — был ли ответ **честно** обрезан (не оборван человеком, не пуст);
 * 2. [reasonAllowsContinue] — означает ли причина остановки именно лимит токенов.
 *
 * Разделение важно, потому что `truncated` экран выставляет сам (по `finish_reason`,
 * см. `LocalChatPresenter`), и если транспорт когда-нибудь ошибётся в маппинге, второй
 * вопрос останется независимой проверкой. Вызывающему, у которого есть `finishReason`,
 * нужно требовать истинности обоих ответов.
 */
object LocalContinuePolicy {

    /**
     * Служебная реплика, которая дописывается в историю перед продолжением.
     *
     * Почему формулировка именно такая:
     * - «с того места, где остановился» — без неё модель склонна пересказать ответ
     *   целиком: обрезанный хвост выглядит как обычное завершение мысли;
     * - «без повторов» — самый частый дефект продолжения: провайдер повторяет
     *   последний абзац, потому что он попал в контекст как «уже сказанное»;
     * - никаких кавычек, номеров сообщений и идентификаторов: реплика уходит в историю
     *   как обычный текст человека, и любая разметка в ней была бы видна модели как
     *   часть просьбы, а не как служебная пометка.
     *
     * Текст короткий намеренно: он тратит токены окна на каждом продолжении, а длинная
     * инструкция не делает продолжение точнее — модель уже видит весь предыдущий ответ.
     */
    const val CONTINUE_PROMPT = "Продолжи ответ с того места, где остановился, без повторов."

    /**
     * Показывать ли предложение продолжить.
     *
     * Только честная обрезка: [truncated] (ответ упёрся в лимит выходных токенов),
     * не [interrupted] (человек нажал «Стоп» или поток упал) и [text] не пустой.
     *
     * Почему обрыв исключён: после «Стоп» продолжение — это уже не дописывание
     * недописанного, а новый ход против воли человека; а после сбоя связи неизвестно,
     * где именно оборвался текст, и продолжение склеит два разных места.
     *
     * Почему пустой текст исключён: обрезка на первом же токене даёт пустой пузырь, и
     * продолжать нечего — правильнее повторить запрос (или уменьшить вложения), а не
     * предлагать «продолжить» пустоту.
     *
     * Пробельный текст считается пустым: модель, отдавшая только переводы строк, ничего
     * не сказала, и кнопка здесь так же бессмысленна, как на пустом ответе.
     */
    fun shouldOffer(truncated: Boolean, interrupted: Boolean, text: String): Boolean =
        truncated && !interrupted && text.isNotBlank()

    /**
     * Разрешает ли причина остановки продолжение.
     *
     * `true` — только [LocalTurnMetrics.REASON_LENGTH] (`length`): провайдер упёрся в
     * лимит выходных токенов, ответ механически недописан, и следующий запрос с той же
     * историей допишет его с того же места.
     *
     * Все остальные причины означают, что продолжать нечего или вредно:
     * - `stop` — модель закончила сама; продолжение вынудит её говорить дальше
     *   законченной мысли и выглядит как «ещё воды»;
     * - `tool_calls` — ход не закончен, а передан инструментам: продолжение оборвало бы
     *   цикл вызовов, который сейчас выполняется;
     * - `content_filter` — ответ остановлен фильтром площадки; повтор той же просьбы
     *   упрётся в тот же фильтр, а формулировка «продолжи» выглядит как обход запрета;
     * - `null` — провайдер причину не сообщил (это норма, а не ошибка): «неизвестно» не
     *   даёт права утверждать, что ответ обрезан, поэтому кнопку не показываем.
     *
     * Сравнение терпимо к регистру и краевым пробелам: часть [OI]-совместимых шлюзов
     * отдаёт `LENGTH` или `" length "`, и терять из-за этого единственный честный
     * признак обрезки нельзя. Незнакомое значение причины — тоже `false`: правило
     * «неизвестно ≠ обрезано».
     */
    fun reasonAllowsContinue(finishReason: String?): Boolean =
        finishReason?.trim()?.equals(LocalTurnMetrics.REASON_LENGTH, ignoreCase = true) == true
}
