package ru.mars.mobile

/**
 * Человеческий текст события [VoiceSubstitution]: «чем именно прозвучала реплика».
 *
 * ## Зачем отдельная политика
 * Резерв голоса — разрешённое поведение, молчаливая подмена — дефект. Раньше событие
 * подмены доходило до движка и там умирало: `LocalVoiceTts` принимал колбэк, а хост его не
 * передавал, поэтому человек, выбравший «Алису», слышал робота Android без единого слова
 * объяснения. Текст сообщения — тоже контракт, а не украшение: он говорит, ЧТО случилось и
 * что делать, и он должен быть одинаковым в обоих чатах (серверном и локальном), иначе
 * один и тот же сбой описывается двумя разными фразами.
 *
 * Класс чистый (никакого `android.*` и состояния), поэтому правила проверяются
 * JVM-тестом, а не приёмкой на телефоне.
 *
 * ## Что НЕ говорится
 * Ни модели, ни кода ошибки, ни текста реплики: человеку нужно понять «почему не тот
 * голос», а не читать `401`. Диагностика остаётся в [RepositoryServerTtsClient.lastAttempts]
 * и логах.
 */
object VoiceSubstitutionNotice {

    /** Облако не дало звука — говорит локальная модель Piper. Это нормальный резерв. */
    const val CLOUD_FAILED: String =
        "Облачный голос не ответил — читаю локальным голосом (Piper)"

    /** Локальная модель не поднялась — говорит облако. Резерв, о котором надо знать. */
    const val OFFLINE_FAILED: String =
        "Локальный голос не поднялся — читаю облачным голосом"

    /** Ни облака, ни локальной модели: звучит платформенный TTS (самый чужой голос). */
    const val SYSTEM_RESERVE: String =
        "Облачный голос недоступен, локальной модели нет — читаю системным голосом"

    /**
     * Выбранный платный голос PlusVibe не прозвучал — фразу прочитал нейро-резерв.
     *
     * Отдельно от [CLOUD_FAILED]: там отказ был у серверного `api/tts`, здесь — у прямого
     * провайдера, и человеку важно понимать, что дело не в Марсе.
     */
    const val PAID_UNAVAILABLE: String =
        "Голос PlusVibe не ответил — читаю другим голосом"

    /**
     * Платный голос выбран, но профиль PlusVibe в настройках не заведён.
     *
     * Это НЕ сетевой сбой и не «провайдер молчит»: чинится одним действием в настройках
     * провайдера. Поэтому текст говорит причину прямо, а не отправляет человека искать
     * проблему в сети.
     */
    const val PLUSVIBE_NOT_CONFIGURED: String =
        "Профиль PlusVibe не настроен — читаю другим голосом"

    /** Короткая форма для узкой строки статуса: та же мысль двумя словами. */
    const val PAID_UNAVAILABLE_SHORT: String = "Говорю другим голосом"

    /**
     * Текст для статусной строки/тоста.
     *
     * Выбор идёт по ФАКТИЧЕСКОМУ каналу ([VoiceSubstitution.spoken]), а причина уточняет
     * формулировку: одинаковый канал может получиться по разным причинам, и человеку важнее
     * «чем говорят сейчас», чем внутренний код. Неизвестная комбинация не оставляет
     * молчания — есть общий текст на канал.
     */
    fun text(substitution: VoiceSubstitution): String = when (substitution.spoken) {
        VoiceChannel.OFFLINE -> CLOUD_FAILED
        VoiceChannel.CLOUD -> OFFLINE_FAILED
        VoiceChannel.SYSTEM -> SYSTEM_RESERVE
    }

    /**
     * Короткая форма для узкой строки статуса (кнопка голоса, шапка композера).
     *
     * Длинный текст полезен один раз, а в статусе он живёт до следующего события и не
     * должен выдавливать подсказку фазы. Короткая форма говорит то же самое двумя словами.
     */
    fun shortText(substitution: VoiceSubstitution): String = when (substitution.spoken) {
        VoiceChannel.OFFLINE -> "Говорю локальным голосом"
        VoiceChannel.CLOUD -> "Говорю облачным голосом"
        VoiceChannel.SYSTEM -> "Говорю системным голосом"
    }

    /**
     * Текст для случая «платный голос PlusVibe не прозвучал».
     *
     * Причина приходит кодом отказа платного клиента, а не каналом: в этой ветке звучит
     * нейро-резерв, и канал у него тот же, что у выбранного голоса. Разделение важное:
     * `no_plusvibe_profile` — это «провайдер не заведён в настройках», остальные коды —
     * «провайдер/сеть не дали звука». Незнакомый код не оставляет человека без объяснения.
     */
    fun paidUnavailable(reason: String?): String = when (reason) {
        PlusVibeTtsProfile.REASON_NO_PROFILE -> PLUSVIBE_NOT_CONFIGURED
        else -> PAID_UNAVAILABLE
    }
}
