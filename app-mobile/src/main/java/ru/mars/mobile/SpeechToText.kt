package ru.mars.mobile

/**
 * Шов распознавания речи: цикл диалога ([VoiceDialogLoop]) зависит от ЭТОГО интерфейса, а не от
 * конкретного движка. Зачем шов:
 *
 * - серверный whisper (`POST /api/transcribe`) даёт 2.8–5.3 с на ЛЮБУЮ фразу — он всегда гоняет
 *   фиксированное 30-секундное окно, поэтому короткое «да» распознаётся столько же, сколько
 *   длинный вопрос. Это и есть тормоз текущего цикла;
 * - потоковый ASR на устройстве отдаёт первый частичный результат за 24–29 мс (RTF ≈ 0.04),
 *   но требует НЕПРЕРЫВНОГО потока PCM и нативной библиотеки, которой может не быть на
 *   конкретной сборке/устройстве;
 * - поэтому реализаций две ([StreamingStt] и [WhisperStt]), и цикл выбирает её по [isReady],
 *   а не по `if (BuildConfig...)`. Пока движок не загружен, диалог продолжается по старому
 *   пути через whisper — без падения и без «немого» микрофона.
 *
 * ## Контракт потоков
 * - [acceptPcm] вызывается С ПОТОКА ЧТЕНИЯ микрофона (см. [HandsFreeCapture.RawPcmListener]):
 *   реализация обязана быть дешёвой и не блокировать чтение;
 * - [startUtterance], [finishUtterance], [cancelUtterance], [release] зовёт хост/цикл с главного
 *   потока;
 * - события [Events] могут прийти с потока движка — хост обязан переложить их на главный поток
 *   (в ChatActivity это `runOnUiThread`), как и колбэки [HandsFreeCapture].
 *
 * ## Что считается концом реплики
 * Endpoint-детекцию делает САМ движок (это его работа и его задержка): когда он выдал
 * [Events.onFinal], реплика закончена и цикл отправляет ход. Таймаут тишины ([VoiceSegmenter])
 * для основного пути не нужен — он остаётся только для whisper-пути, где резать поток нечем.
 * Если endpoint не сработал (человек замолчал «на полуслове», шум), хост зовёт
 * [VoiceDialogLoop.stopUtterance], и [finishUtterance] отдаёт финальный текст принудительно.
 *
 * Чистый JVM: ни одного импорта Android, поэтому обе реализации и сам цикл проверяются
 * юнит-тестами на фейковом движке/фейковом транспорте, без нативной библиотеки и без сети.
 */
interface SpeechToText {

    /** Короткое имя для логов и диагностики: «streaming-asr», «whisper». */
    val id: String

    /**
     * Готов ли движок принимать звук прямо сейчас. `false` — цикл обязан работать по
     * whisper-пути (плавная деградация), а не ждать и не падать.
     */
    val isReady: Boolean

    /** Начать новую реплику: сбросить состояние распознавания и открыть приём PCM. */
    fun startUtterance()

    /**
     * Скормить очередной буфер PCM16 (16 кГц, моно, little-endian). [length] — сколько байт в
     * [pcm] валидно; буфер переиспользуется вызывающим, поэтому реализация не имеет права его
     * сохранять. Звук, пришедший вне реплики (до [startUtterance] или после [finishUtterance]),
     * отбрасывается: иначе хвост озвучки ответа попал бы в следующую реплику.
     */
    fun acceptPcm(pcm: ByteArray, length: Int)

    /**
     * Принудительно закончить реплику (ручной стоп) и отдать её текст.
     *
     * Возвращает:
     * - непустой текст — распознавание уже готово, цикл отправляет его сразу;
     * - `""` — в реплике нечего распознавать (тишина/щелчок);
     * - `null` — текста синхронно нет, он придёт событием [Events.onFinal] (так работает
     *   [WhisperStt]: сеть асинхронна). Цикл в этом случае продолжает ЖДАТЬ финал и не
     *   считает реплику закрытой.
     */
    fun finishUtterance(): String?

    /** Выбросить текущую реплику без текста (режим выключили, экран ушёл в фон). */
    fun cancelUtterance()

    /** Освободить движок/модель. После вызова [isReady] == false. */
    fun release()

    /** Куда реализация отдаёт события. Ставит цикл; `null` — события никому не нужны. */
    var events: Events?

    /** События распознавания. Все методы имеют пустую реализацию: реализация шлёт только то, что умеет. */
    interface Events {
        /** Движок услышал начало речи (для barge-in и статуса «слушаю»). */
        fun onSpeechStarted() {}

        /** Промежуточный результат: хост показывает живой транскрипт. */
        fun onPartial(text: String) {}

        /** Endpoint: реплика закончена, [text] — финальный текст. */
        fun onFinal(text: String) {}

        /** Движок сломался: цикл уходит на whisper-путь, диалог продолжается. */
        fun onFailed(reason: String) {}
    }
}
