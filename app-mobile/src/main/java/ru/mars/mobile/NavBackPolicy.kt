package ru.mars.mobile

/**
 * Чистая политика системного Back для двухуровневого мобильного навигатора.
 *
 * Продуктовая лестница волны 2: **чат → диалоги → разделы (левый бар) →
 * системный выход**. Уровни хостят разные экраны: диалог — ChatActivity,
 * список диалогов (корень раздела [AppDestination.CHAT]) — ChatSessionsActivity;
 * разделы — шторка левого бара, доступная на обоих экранах.
 *
 * Связь с [AppNavPolicy]: на уровне диалога ([ChatLevel.Session]) back по
 * политике всегда возвращает корень CHAT (список диалогов) — ChatActivity
 * никогда не является корнём раздела, поэтому системный выход из чата
 * недостижим. На корневом уровне [AppNavPolicy.back] возвращает null
 * («выход из приложения решает UI-слой»): здесь UI-решение — сначала показать
 * разделы (шторку), и лишь повторный Back из показанных разделов завершает
 * приложение.
 *
 * Политика не знает об Activity/View: экран сообщает, какой он уровень и
 * какие оверлеи открыты, а UI-слой исполняет полученное действие.
 */
object NavBackPolicy {

    /** Экран-уровень навигатора, для которого обрабатывается Back. */
    enum class Level {
        /** Уровень диалога (ChatActivity): открытый диалог или новый чат. */
        CHAT,

        /** Корень раздела CHAT (ChatSessionsActivity): список диалогов. */
        SESSION_LIST,
    }

    /** Действие UI-слоя на одно нажатие Back. */
    enum class Action {
        /** Закрыть панель поиска (по транскрипту в чате). */
        CLOSE_SEARCH,

        /** Закрыть шторку разделов, оставшись на уровне диалога. */
        CLOSE_DRAWER,

        /** Показать разделы (левый бар): шаг «диалоги → разделы». */
        OPEN_DRAWER,

        /** Перейти на уровень списка диалогов: шаг «чат → диалоги». */
        GO_TO_SESSION_LIST,

        /** Дальше некуда (разделы показаны на корневом уровне): системный выход. */
        SYSTEM_EXIT,
    }

    /**
     * Решение для одного нажатия Back.
     *
     * Уровень диалога: поиск по транскрипту закрывается первым; шторка
     * разделов — оверлей НАД диалогом, поэтому Back закрывает её и оставляет
     * пользователя на уровне диалога; без оверлеев Back ведёт на уровень
     * списка диалогов.
     *
     * Уровень списка: список — корень раздела CHAT, Back показывает разделы
     * (шторку); Back из уже показанных разделов — системный выход.
     */
    fun resolve(level: Level, searchOpen: Boolean, drawerOpen: Boolean): Action = when (level) {
        Level.CHAT -> when {
            searchOpen -> Action.CLOSE_SEARCH
            drawerOpen -> Action.CLOSE_DRAWER
            else -> Action.GO_TO_SESSION_LIST
        }
        Level.SESSION_LIST -> when {
            searchOpen -> Action.CLOSE_SEARCH
            drawerOpen -> Action.SYSTEM_EXIT
            else -> Action.OPEN_DRAWER
        }
    }

    /**
     * Контрактная лестница Back от уровня диалога до системного выхода —
     * ровно три шага: чат → диалоги → разделы → выход.
     */
    fun backLadder(): List<Action> = listOf(
        Action.GO_TO_SESSION_LIST,
        Action.OPEN_DRAWER,
        Action.SYSTEM_EXIT,
    )
}
