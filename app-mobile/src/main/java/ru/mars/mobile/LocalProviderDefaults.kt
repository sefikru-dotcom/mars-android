package ru.mars.mobile

/**
 * Заводские значения локального провайдера.
 *
 * Зачем отдельный объект, а не строки по месту: адрес и модель нужны минимум в двух
 * точках — в форме настроек (предзаполнение) и при первом старте, когда профиля ещё
 * нет. Разъехавшиеся константы дают ровно тот дефект, который уже ловили на POCO F5:
 * в одном месте «plusvibeapi.ru/v1», в другом пусто — и «Проверить» ругается на
 * незаполненный адрес при заполненном с виду экране.
 *
 * Модель — та же, что дефолт Марса (`claude-haiku-5.5`): локальный чат не должен
 * неожиданно уходить на другую модель только потому, что включён другой режим.
 *
 * Ключ здесь НЕ хранится: он вводится человеком один раз и живёт в AndroidKeyStore
 * ([LocalProviderPrefsStore]). Зашитый в APK ключ достаётся из архива одной командой.
 */
internal object LocalProviderDefaults {

    /** Адрес по умолчанию (OpenAI-совместимый, тот же провайдер, что у сервера). */
    const val BASE_URL = "https://plusvibeapi.ru/v1"

    /** Модель по умолчанию. */
    const val MODEL = "claude-haiku-5.5"

    /** Название профиля по умолчанию — по нему строка в списке читается без домыслов. */
    const val TITLE = "PlusVibe"
}
