package ru.mars.mobile

/**
 * Строка «запомнил» под ответом: что именно и когда.
 *
 * [text] — сам факт без префикса: префикс «Запомнил: » добавляет [MemoryNoticePolicy.render],
 * иначе он попал бы в строку дважды (инструмент уже отдаёт его в своём ответе, а экран
 * строит её заново). [at] — момент показа, мс по `System.currentTimeMillis()`: по нему
 * считается срок жизни подсказки, а не по времени записи в память — человеку важно,
 * сколько подсказка висит у него на экране.
 *
 * Почему это данные, а не View: строка «запомнил» — единственное, что видит человек,
 * когда модель молча пишет факт в память. Решение «показывать ли» и «как обрезать»
 * проверяется JVM-тестом без эмулятора, а [MemoryNoticeView] только рисует готовую строку.
 */
data class MemoryNotice(
    val text: String,
    val at: Long,
) {
    /** Показывать ли подсказку: пустой факт — не подсказка, а пустая полоска в ленте. */
    val isVisible: Boolean get() = text.isNotBlank()
}

/**
 * Политика подсказки «запомнил»: разбор ответа инструмента `remember`, строка для ленты
 * и срок её жизни.
 *
 * Ни одного импорта `android.*` — здесь только строки и арифметика над временем, поэтому
 * правила проверяются обычным JVM-тестом (`MemoryNoticePolicyTest`), а не эмулятором.
 *
 * ## Зачем подсказка вообще
 *
 * `remember` пишет факт в память молча: инструмент отдаёт модели «Запомнил: …», модель
 * продолжает разговор, и человек не видит, что именно о нём отложилось. Экран памяти
 * (`LocalMemoryActivity`) есть, но он в другом месте и не в моменте — чтобы заметить
 * неверно записанный факт, надо уйти с экрана чата. Строка под ответом возвращает
 * человеку момент: видно, что записалось, и можно сразу возразить или почистить память.
 *
 * ## Почему на неудаче подсказки нет
 *
 * Формат ответа инструмента (сверено с `RememberTool.kt`, не выдуман):
 * - успех — `toolOk("Запомнил: <факт>")`;
 * - отказ хранилища — `toolError("В память не записано: <причина>")` (переполнение,
 *   разделитель `§`, нечитаемые символы, диск не принял запись);
 * - отказ валидации — `"Не указан обязательный аргумент text…"`, `"Факт слишком длинный…"`.
 *
 * Подсказка «запомнил» на неудаче хуже её отсутствия: человек уверен, что факт сохранён,
 * а в памяти пусто. Поэтому [fromToolResult] пропускает **только** строки с префиксом
 * успеха, всё остальное — `null`.
 *
 * Отдельного исхода «дубль» в `MemoryStore` нет: `add` проверяет пустоту, разделитель,
 * нечитаемые символы и лимит `MAX_CHARS`, но не сравнивает запись с уже существующими.
 * Повторный тот же факт сохраняется второй раз и отвечает успехом — значит и подсказка
 * показывается. Дубликат — вопрос хранилища, а не этой политики: здесь нет и не должно
 * быть списка фактов, иначе политика перестанет быть чистой.
 */
object MemoryNoticePolicy {

    /** Сколько живёт подсказка в ленте, мс. */
    const val LIFETIME_MS: Long = 60_000L

    /**
     * Предел длины строки в ленте, символы — **вместе с префиксом** «Запомнил: ».
     *
     * Почему префикс входит в предел: в ленте строка живёт одной строкой с
     * `ellipsize = END` на узкой полоске, и обрезать надо то, что реально нарисовано,
     * а не только факт. 120 символов при 12sp — примерно две ширины узкого телефона,
     * дальше начало обрезается многоточием и факт всё равно не прочитать.
     */
    const val MAX_CHARS: Int = 120

    /** Префикс успешного ответа инструмента `remember` (см. `RememberTool.kt`). */
    const val PREFIX: String = "Запомнил: "

    /** Чем помечается обрезка: многоточие, а не три точки — один символ, одна ширина. */
    private const val ELLIPSIS: String = "…"

    /**
     * Разобрать результат вызова `remember` в строку для человека.
     *
     * Возвращает `null`, если факт не записан: пустая строка, любой отказ инструмента
     * (все они начинаются иначе), успех с пустым фактом. `nowMs` становится [MemoryNotice.at] —
     * политика не читает часы сама: время приходит снаружи, иначе тест зависел бы от
     * системных часов, а на устройстве строка могла бы «истечь» в момент создания.
     *
     * Края срезаются до сверки префикса: ответ инструмента приходит из JSON-обвязки и
     * может приехать с завершающим переводом строки, но лишний пробел в начале не должен
     * превращать успех в «не записано».
     */
    fun fromToolResult(result: String, nowMs: Long): MemoryNotice? {
        val line = result.trim()
        if (!line.startsWith(PREFIX)) return null
        val fact = line.substring(PREFIX.length).trim()
        if (fact.isEmpty()) return null
        return MemoryNotice(text = fact, at = nowMs)
    }

    /**
     * Строка для ленты: «Запомнил: …», обрезанная до [MAX_CHARS] с многоточием.
     *
     * Пустой факт даёт пустую строку, а не голый префикс: «Запомнил: » без содержания —
     * это подсказка ни о чём, и [MemoryNoticeView] по пустой строке прячется целиком.
     *
     * Пробелы в конце срезаются перед многоточием: обрезка ровно по границе слова иначе
     * даёт «… факт …» с висящим пробелом перед точкой.
     */
    fun render(notice: MemoryNotice): String {
        val line = fullText(notice)
        if (line.length <= MAX_CHARS) return line
        return cut(line, MAX_CHARS).trimEnd() + ELLIPSIS
    }

    /**
     * Полная строка без обрезки — для TalkBack и копирования.
     *
     * Нужна отдельно от [render], потому что в ленте текст обрезан, а озвучивать
     * обрезанное бессмысленно: диктор прочитает «Запомнил: Владельца зовут…» и оборвётся
     * на самом интересном месте.
     */
    fun fullText(notice: MemoryNotice): String {
        val fact = notice.text.trim()
        return if (fact.isEmpty()) "" else PREFIX + fact
    }

    /**
     * Пора ли убрать подсказку из ленты: `nowMs - notice.at >= LIFETIME_MS`.
     *
     * Граница включительная: ровно на [LIFETIME_MS] подсказка уже истекла. Отдельного
     * «ещё чуть-чуть» нет — иначе два вызова с одинаковым временем давали бы разные
     * ответы в зависимости от порядка проверок.
     *
     * Часы, ушедшие назад (ручная правка времени, перевод зоны), дают отрицательную
     * разницу и `false`: подсказка просто повисит дольше — это безопаснее, чем исчезнуть
     * в момент появления.
     */
    fun isExpired(notice: MemoryNotice, nowMs: Long): Boolean =
        nowMs - notice.at >= LIFETIME_MS

    /**
     * Сколько фактов в памяти — для подписи «всего N фактов».
     *
     * `count < 0` — «неизвестно»: файла памяти нет или его не прочитали, и врать числом
     * нельзя. Сигнатура возвращает `String`, а не `String?` (так в контракте), поэтому
     * «неизвестно» — пустая строка: вызывающий просто не приписывает подпись.
     *
     * Слово согласуется с числом («1 факт», «3 факта», «12 фактов»): подпись стоит рядом
     * с русским текстом подсказки, и «всего 3 факт» в ленте выглядит опечаткой.
     */
    fun countHint(count: Int): String {
        if (count < 0) return ""
        return "всего $count ${factWord(count)}"
    }

    /**
     * Обрезка до [limit] символов без разрыва суррогатной пары.
     *
     * `take` режет по единицам UTF-16, а эмодзи занимает две: обрезка ровно между ними
     * даёт одиночный суррогат, и в ленте вместо эмодзи появляется пустой прямоугольник. На
     * тексте без эмодзи поведение ровно `take(limit)` — то есть «120 символов плюс многоточие».
     */
    private fun cut(line: String, limit: Int): String {
        val head = line.take(limit)
        return if (head.isNotEmpty() && head.last().isHighSurrogate()) head.dropLast(1) else head
    }

    /** Русское согласование слова «факт» с числом: 11–14 — всегда «фактов». */
    private fun factWord(count: Int): String {
        val tail = count % 100
        return when {
            tail in 11..14 -> "фактов"
            count % 10 == 1 -> "факт"
            count % 10 in 2..4 -> "факта"
            else -> "фактов"
        }
    }
}
