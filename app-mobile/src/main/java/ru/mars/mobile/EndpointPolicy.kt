package ru.mars.mobile

/**
 * Что решил детектор конца реплики.
 *
 * Два состояния, а не три: «ещё слушаю» и «реплика закончена». Промежуточного
 * «наверное закончил» нет намеренно — решение должно быть исполняемым, иначе хост
 * начнёт трактовать неопределённость по-своему в двух местах.
 */
enum class EndpointDecision {
    KEEP_LISTENING,
    END_UTTERANCE,
}

/**
 * Признаки конца реплики, снятые по хвосту УЖЕ имеющегося PCM.
 *
 * Зачем отдельный тип, а не аргументы функции: признаков пять, и они приходят из трёх
 * разных мест (детектор тишины, счётчик RMS, движок распознавания). Пять `Long`/`Int` в
 * сигнатуре перепутать местами — вопрос времени, а `data class` ещё и печатается в лог
 * целиком при разборе «почему не закончил».
 *
 * Ни одного `android.*`: считается на JVM, тестируется синтетикой. Время приходит
 * параметром, часы внутрь не зашиты — иначе тест зависел бы от реального времени.
 *
 * @param silenceMs длительность тишины на хвосте;
 * @param lastSpeechRms RMS последнего речевого чанка: «голос упал» — человек закончил мысль;
 * @param averageSpeechRms средний уровень голоса на плато последних ~400 мс — база сравнения;
 * @param lastWords последний распознанный текст (у потокового ASR может быть пустым);
 * @param sinceLastFinalMs сколько прошло с последнего финального результата распознавания.
 */
data class EndpointFeatures(
    val silenceMs: Long,
    val lastSpeechRms: Int,
    val averageSpeechRms: Int,
    val lastWords: String = "",
    val sinceLastFinalMs: Long = 0L,
) {

    /** Уровень упал заметно ниже своего же плато: типичный признак законченной фразы. */
    val levelDropped: Boolean
        get() = averageSpeechRms > 0 && lastSpeechRms < averageSpeechRms * LEVEL_DROP_RATIO

    private companion object {
        /** Падение до 55 % от плато: шум комнаты так не проседает, а конец фразы — да. */
        const val LEVEL_DROP_RATIO: Float = 0.55f
    }
}

/**
 * Политика «реплика закончена»: умный конец фразы поверх обычного детектора тишины.
 *
 * Зачем отдельный объект. [SilenceDetector] и [VoiceSegmenter] закрывают реплику по одному
 * признаку — тишина дольше `hangover`. Из-за этого быстрый ответ ждёт лишние 300–600 мс, а фраза,
 * оборванная на «…и», всё равно обрывается: пауза-раздумье посреди предложения по RMS ничем не
 * отличается от паузы в конце. Здесь к тишине добавлены два дешёвых смысловых признака, которые
 * уже есть в потоке: последнее слово (оборвана ли мысль) и падение уровня (человек договорил и
 * выдохнул). Порядок проверок в [decide] — это лестница компромиссов, и он важен:
 *
 * 1. [HARD_SILENCE_MS] — предохранитель. Держать микрофон дольше бессмысленно: даже при оборванной
 *    фразе продолжение уже не придёт, а разговор стоит. Здесь решение не оспаривается.
 * 2. Оборванная мысль — наоборот, повод подождать: «я хотел сказать, что» почти никогда не конец,
 *    и закрыть такую реплику раньше жёсткого предела значит потерять продолжение.
 * 3. Штатный `hangover` — обычный конец: пауза выдержана, текст цельный.
 * 4. Мягкий порог [SOFT_SILENCE_MS] работает только вместе с падением уровня: короткая пауза сама
 *    по себе ничего не значит (человек делает вдох), но короткая пауза ПОСЛЕ просевшего голоса —
 *    это уже точка.
 *
 * Почему признаки именно такие. Полноценная semantic VAD — это модель; на устройстве без сети её
 * нет, а тянуть её ради одного бита «закончил ли человек» несоразмерно. Предлог/союз в конце и
 * запятая в конце — самые частые следы оборванной фразы в тексте ASR, а падение RMS — единственный
 * акустический признак, который не путается с шумом комнаты. Асимметрия ошибок оправдывает такую
 * грубость: ошибка «подождать» стоит 300–600 мс ожидания, ошибка «обрезать» — потерянных слов,
 * которые человеку придётся повторять.
 *
 * Объект чистый (ни одного `android.*`), без состояния и без часов: всё приходит в
 * [EndpointFeatures]. Поэтому правила проверяются таблицей «входы → решение», без микрофона и без
 * реального времени.
 *
 * @see EndpointFeatures.levelDropped готовый признак падения уровня (55 % от плато).
 */
object EndpointPolicy {

    /**
     * Порог тишины, после которого думать о смысле уже поздно: реплика закрывается всегда.
     *
     * 1.6 с — это заметно больше штатного `hangover` (1.2 с) и меньше, чем человек терпит молчание
     * собеседника. Значение выбрано как «верхняя граница ожидания»: сюда доходит только реплика,
     * которую политика уже пыталась продолжить, и дальше задерживать её незачем.
     */
    const val HARD_SILENCE_MS: Long = 1_600L

    /**
     * Минимальная тишина, при которой «короткое слово» уже может закончить реплику.
     *
     * Ниже этого порога не закрываем реплику ни при каком падении уровня: 550 мс — типичная пауза
     * между словами и на вдохе, и резать по ней значит рвать фразу на каждом втором слове.
     */
    const val SOFT_SILENCE_MS: Long = 550L

    /**
     * Решить судьбу текущей реплики по снятым признакам хвоста.
     *
     * @param features признаки хвоста: тишина, RMS последнего чанка и плато, последний текст ASR;
     * @param hangoverMs штатная пауза конца реплики у хоста (по умолчанию 1.2 с — как у
     *   [SilenceDetector.DEFAULT_HANGOVER_MS]). Отрицательное значение приводится к нулю: политика
     *   не должна падать из-за опечатки в настройке, а «нулевой hangover» — это законное «решать
     *   только по смыслу и уровню».
     *
     * Порядок проверок описан в KDoc объекта: жёсткий предел → оборванная мысль → `hangover` →
     * мягкий порог с падением уровня. Пустой [EndpointFeatures.lastWords] даёт
     * `looksIncomplete == false`, то есть потоковый ASR без текста честно работает по RMS-веткам.
     *
     * `sinceLastFinalMs` намеренно не участвует в решении: свежесть финала ASR говорит о движке, а
     * не о человеке — у потокового распознавания финал может не приходить вовсе, и запрещать из-за
     * этого конец реплики значило бы зависеть от реализации ASR.
     */
    fun decide(features: EndpointFeatures, hangoverMs: Long = 1_200L): EndpointDecision {
        val silenceMs = features.silenceMs.coerceAtLeast(0L)
        val hangover = hangoverMs.coerceAtLeast(0L)

        // 1. Жёсткий предел: даже оборванная фраза не оправдывает бесконечное ожидание.
        if (silenceMs >= HARD_SILENCE_MS) return EndpointDecision.END_UTTERANCE

        // 2. Мысль оборвана — ждём продолжения. Проверка идёт ДО hangover: иначе пауза в конце
        //    «… и» закрывала бы реплику ровно тем же правилом, что и законченную фразу.
        if (looksIncomplete(features.lastWords)) return EndpointDecision.KEEP_LISTENING

        // 3. Штатный hangover: пауза выдержана и текст цельный — это конец.
        if (silenceMs >= hangover) return EndpointDecision.END_UTTERANCE

        // 4. Мягкий порог: только когда голос уже просел — короткая пауза плюс падение уровня.
        if (silenceMs >= SOFT_SILENCE_MS && features.levelDropped) {
            return EndpointDecision.END_UTTERANCE
        }

        // Всё остальное — ещё слушаем: пауза короткая либо уровень держится (человек думает
        // вслух, делает вдох, тянет гласную).
        return EndpointDecision.KEEP_LISTENING
    }

    /**
     * Обрывается ли фраза «на полуслове».
     *
     * Признаки, по которым это видно в тексте ASR:
     * - последнее слово — служебное (предлог, союз, частица, относительное местоимение): «… и»,
     *   «… потому», «… который». Такое слово не может закончить мысль, значит продолжение идёт;
     * - текст кончается на запятую, тире, двоеточие или многоточие — знак того, что перечисление
     *   или придаточное не закрыто.
     *
     * Регистр и обрамляющие кавычки/скобки не важны: `«Билет, »` и `билет,` — один и тот же хвост.
     * Запятая в СЕРЕДИНЕ ничего не значит: «Сколько стоит, билет» — цельная фраза, потому что
     * смотрим только на последний значимый символ.
     *
     * Точка, `!` и `?` в конце — наоборот, явный конец: «Что?» — законченный вопрос, хотя последнее
     * слово служебное. Без этого правила короткий вопрос с вопросительным знаком висел бы до
     * [HARD_SILENCE_MS].
     *
     * Пустая строка (потоковый ASR ещё не дал текста) — не incomplete: признак просто неизвестен, и
     * решение обязано опираться на RMS, а не на догадку.
     */
    fun looksIncomplete(lastWords: String): Boolean {
        val tail = significantTail(lastWords) ?: return false
        val last = tail.last()

        // Двоеточие здесь же: «… вот что:» — тот же незакрытый хвост, что и запятая.
        if (last in TRAILING_HINTS) return true
        if (last == ELLIPSIS_CHAR || tail.endsWith(ELLIPSIS)) return true
        // Точка/восклицание/вопрос закрывают мысль даже служебным словом — см. KDoc.
        if (last in SENTENCE_END) return false

        return lastWord(tail) in DANGLING_WORDS
    }

    /**
     * Уверенность 0..1: насколько хвост похож на конец фразы.
     *
     * Складывается из трёх составляющих, каждая — по своему признаку:
     * - **тишина** ([SILENCE_WEIGHT]): линейно растёт от 0 до [HARD_SILENCE_MS] и дальше не растёт.
     *   Линейно — потому что монотонность важна вызывающему: политику можно использовать как
     *   «насколько мы близки к концу» для адаптивных порогов и для UI, и скачок в середине шкалы
     *   сломал бы такую логику;
     * - **падение уровня** ([DROP_WEIGHT]): доля просадки последнего RMS относительно плато. Голос,
     *   который не просел вовсе, вклада не даёт;
     * - **оборванный хвост** ([INCOMPLETE_FACTOR]): не вычитание, а множитель — при обрыве фразы
     *   даже большая тишина не должна выглядеть концом. Множитель, а не минус, чтобы уверенность не
     *   уходила в минус на коротких паузах.
     *
     * Значение зажато в 0..1: вызывающему не нужно думать о диапазоне. При `averageSpeechRms <= 0`
     * (плато ещё не набрано) вклада падения нет — делить на ноль нельзя, а «нет данных» не должно
     * выглядеть как «уровень упал».
     */
    fun confidence(features: EndpointFeatures): Float {
        val silenceMs = features.silenceMs.coerceAtLeast(0L)
        val silenceRatio =
            (silenceMs.toFloat() / HARD_SILENCE_MS.toFloat()).coerceIn(0f, 1f)
        val dropRatio = levelDropRatio(features)

        var value = SILENCE_WEIGHT * silenceRatio + DROP_WEIGHT * dropRatio
        if (looksIncomplete(features.lastWords)) value *= INCOMPLETE_FACTOR
        return value.coerceIn(0f, 1f)
    }

    /**
     * Объяснение решения для лога — БЕЗ текста реплики.
     *
     * Приватность: распознанный текст в логи не попадает никогда (журнал может уйти в отчёт об
     * ошибке), поэтому здесь только числа и производные флаги. «Хвост оборван» — это результат
     * [looksIncomplete], а не цитата: по такой строке видно, какое правило сработало, но не видно,
     * что человек сказал.
     *
     * Формат — одна строка для `Log.d`: вердикт, тишина с порогами, уровень, флаг хвоста.
     * `hangover` сюда не входит: он параметр вызова, а не свойство признаков, и его печатает хост,
     * если ему нужно.
     */
    fun reason(features: EndpointFeatures, decision: EndpointDecision): String {
        val silenceMs = features.silenceMs.coerceAtLeast(0L)
        val tail = if (looksIncomplete(features.lastWords)) "оборван" else "цельный"
        val level = if (features.levelDropped) "упал" else "ровный"
        val plateau = if (features.averageSpeechRms > 0) {
            "${features.lastSpeechRms}/${features.averageSpeechRms}"
        } else {
            "${features.lastSpeechRms}/—"
        }
        return "${decision.name}: тишина $silenceMs мс " +
            "(жёсткий $HARD_SILENCE_MS, мягкий $SOFT_SILENCE_MS), " +
            "RMS $plateau ($level), хвост $tail, с финала ${features.sinceLastFinalMs} мс"
    }

    // --- внутреннее ---------------------------------------------------------------------------

    /**
     * Хвост без пробелов и обрамляющих кавычек/скобок; null — текста нет.
     *
     * Кавычки снимаются в цикле: диктовка и ASR выдают `«билет,»`, `"билет,"` и `(билет,)`, и без
     * нормализации знак конца фразы оказывался бы не последним символом, а предпоследним.
     */
    private fun significantTail(raw: String): String? {
        var text = raw.trim()
        while (text.isNotEmpty() && text.last() in CLOSING_MARKS) {
            text = text.dropLast(1).trimEnd()
        }
        return text.ifEmpty { null }
    }

    /**
     * Последнее слово хвоста в нижнем регистре.
     *
     * Дефис считается частью слова: иначе «как-то» распалось бы на «то» и фраза ложно считалась бы
     * оборванной. Всё остальное (пробел, запятая, кавычка) — граница слова.
     */
    private fun lastWord(tail: String): String {
        var index = tail.length
        while (index > 0) {
            val ch = tail[index - 1]
            if (ch.isLetterOrDigit() || ch == '-' || ch == '\'') index-- else break
        }
        return tail.substring(index).lowercase()
    }

    /** Доля просадки последнего RMS относительно плато, 0..1. Плато нет — просадки нет. */
    private fun levelDropRatio(features: EndpointFeatures): Float {
        val average = features.averageSpeechRms
        if (average <= 0) return 0f
        val drop = (average - features.lastSpeechRms).toFloat() / average.toFloat()
        return drop.coerceIn(0f, 1f)
    }

    /** Вес тишины в [confidence]: основной признак, поэтому доминирует. */
    private const val SILENCE_WEIGHT: Float = 0.75f

    /** Вес падения уровня: подтверждающий признак, не решающий. */
    private const val DROP_WEIGHT: Float = 0.25f

    /** Множитель для оборванного хвоста: сильно гасит уверенность, но не обнуляет её. */
    private const val INCOMPLETE_FACTOR: Float = 0.35f

    /** Знаки, с которых начинается следующий фрагмент мысли. */
    private const val TRAILING_HINTS = ",—–-:"

    /** Явный конец фразы: после такого знака служебное слово уже не признак обрыва. */
    private const val SENTENCE_END = ".!?"

    /** Обрамляющие знаки, которые ASR/диктовка добавляет вокруг реплики. */
    private const val CLOSING_MARKS = "\"'»)]}”’"

    /** Символ многоточия: пауза-раздумье, мысль не закрыта. */
    private const val ELLIPSIS_CHAR = '…'

    /** Три точки вместо многоточия — тот же смысл. */
    private const val ELLIPSIS = "..."

    /**
     * Служебные слова, которые не могут закончить мысль.
     *
     * Список намеренно шире «минимума из контракта»: предлоги, союзы, частицы и относительные
     * местоимения. Лишнее слово в списке стоит одного лишнего ожидания (до [HARD_SILENCE_MS]),
     * пропущенное — обрезанной фразы, поэтому сомнительные случаи решаются в пользу ожидания.
     * Местоимения вроде «это», «так» не включены: они часто заканчивают фразу сами по себе
     * («вот так», «это оно»), и ждать после них было бы уже вредно.
     */
    private val DANGLING_WORDS: Set<String> = (
        "и а но или либо что чтобы чтоб как когда если пока чем поскольку потому поэтому хотя " +
            "который которая которое которые которых которым которого которой которыми чей чья чьё чьи " +
            "в во на с со для по при от о об обо из изо к ко у до за над под про через без между " +
            "около кроме после перед вместо вокруг вдоль среди сквозь ради " +
            "же ли бы не ни ну ведь вот даже только тоже также то"
        ).split(' ').toSet()
}
