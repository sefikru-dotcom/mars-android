package ru.mars.mobile.tts

/**
 * Порт к офлайн-синтезу речи — ровно те вызовы, которые нужны голосовому циклу.
 *
 * Зачем интерфейс без `android.*`: синтез на sherpa-onnx тянет нативный `.so`, поэтому
 * JVM-тесты цикла (и политика «что и когда говорить») не должны собираться только ради
 * того, чтобы подменить движок. Хост видит [OfflineTtsPort], реальная реализация —
 * [OfflineTtsBackend]; в тестах — фейк, который пишет вызовы в список.
 *
 * Контракт по потокам:
 * - [speak] НЕ блокирует: он принимает реплику и возвращает `true`, если звук будет
 *   (синтез и воспроизведение идут в своём потоке). Ошибка синтеза после `true` не
 *   пробрасывается — реплика просто не зазвучит;
 * - [stop] можно звать с любого потока: он обязан прервать и синтез, и воспроизведение,
 *   а не только «дождаться конца»;
 * - [prepare] — `suspend`, потому что скачивание модели и создание нативного движка
 *   занимают секунды; звать из `Dispatchers.IO`-контекста хоста (сам он тоже уходит с
 *   главного потока);
 * - [release] освобождает нативные ресурсы; повторный вызов и вызовы после него безопасны.
 *
 * Реализация не обязана быть потокобезопасной для параллельных [speak]: вторая реплика
 * заменяет первую (перебивание), а не встаёт в очередь.
 */
interface OfflineTtsPort {

    /**
     * Скачать (если нужно) и поднять движок.
     *
     * @return `true` — движок готов, [isReady] начнёт отдавать `true`; `false` — модели нет
     *   и скачать не удалось (нет сети, битый архив, нет места) либо нативный слой не
     *   принял конфиг. Хост в этом случае остаётся на серверном/системном TTS и не
     *   повторяет [prepare] на каждой фразе.
     */
    suspend fun prepare(): Boolean

    /**
     * Озвучить [text] (целиком, одной репликой).
     *
     * @return `true` — реплика принята и будет звучать; `false` — движок не готов
     *   ([prepare] не звали или он отказал), текст пуст после `trim` или бэкенд уже
     *   освобождён.
     */
    fun speak(text: String): Boolean

    /** Немедленная тишина: прервать синтез и воспроизведение. Безопасно без активной реплики. */
    fun stop()

    /** Движок поднят и может синтезировать (модель на диске, нативный объект жив). */
    fun isReady(): Boolean

    /** Освободить нативные ресурсы и поток синтеза. Повторный вызов безопасен. */
    fun release()
}
