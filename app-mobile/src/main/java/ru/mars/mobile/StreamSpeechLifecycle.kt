package ru.mars.mobile

/**
 * Жизненный цикл потоковой озвучки ОДНОГО хода.
 *
 * Хост задаёт три вопроса, и раньше на все три отвечал один `Boolean`:
 * 1. озвучивается ли ход вообще ([isSpeechEnabled]) — решение принимается один раз на старте;
 * 2. можно ли отдать в синтез ещё текст ([acceptsDelta]);
 * 3. закончился ли ответ — то есть пора ли циклу снова слушать ([onQueueDrained]).
 *
 * Почему это разные вопросы. Очередь фраз ([SpeechQueue]) опустошается в любой момент: между
 * фразами, после «Проверяю…», пока инструмент ещё работает, на паузе перед второй половиной
 * ответа. «В динамике тихо» ≠ «ответ закончился»: второе знает только ход (терминальный `Done`
 * или конец стрима). Пока конец хода не объявлен, опустевшая очередь — это пауза, и поздние
 * дельты обязаны звучать дальше.
 *
 * Отсюда инварианты:
 * - [onQueueDrained] возвращает `true` только ПОСЛЕ [end] и ровно один раз: цикл слышит
 *   «ответ закончился» один раз на ход, а не на каждую паузу;
 * - [acceptsDelta] ложно после [end]: хвост после `Done` не дозвучивает прошлый ход;
 * - [cancel] (стоп/перебивание) гасит ход насовсем и НЕ взводит отменённую очередь: поздний
 *   `drained` от уже очищенной очереди не должен ни озвучивать, ни «завершать» ответ;
 * - [begin] полностью сбрасывает состояние прошлого хода.
 *
 * Класс чистый (JVM, без Android): поведение проверяется юнит-тестами без устройства.
 */
class StreamSpeechLifecycle {

    /** Ход озвучивается потоково: его текст имеет право попасть в синтез. */
    var isSpeechEnabled: Boolean = false
        private set

    /** Ход объявил конец ответа ([end]); новых фраз не будет, очередь только доигрывает. */
    var isTurnEnded: Boolean = false
        private set

    /** Новый ход: решение об озвучке фиксируется здесь и не меняется до конца хода. */
    fun begin(enabled: Boolean) {
        isSpeechEnabled = enabled
        isTurnEnded = false
    }

    /**
     * Дельта ответа: отдавать ли её в синтез.
     *
     * Пауза в аудио сюда не входит — только конец хода: иначе вторая половина ответа, пришедшая
     * после «Проверяю…» или после первой доигравшей фразы, осталась бы без звука.
     */
    val acceptsDelta: Boolean
        get() = isSpeechEnabled && !isTurnEnded

    /** Ход завершён (Done / конец стрима): новых фраз не будет, очередь доигрывает остаток. */
    fun end() {
        isTurnEnded = true
    }

    /** Ход отменён/прерван: тишина немедленно, хвост ответа не догоняет. */
    fun cancel() {
        isSpeechEnabled = false
        isTurnEnded = true
    }

    /**
     * Очередь фраз опустела и всё доиграно.
     *
     * @return `true`, если циклу пора услышать «ответ закончился»: только когда ход уже объявил
     *   конец ответа, и только один раз. Пауза внутри живого хода — `false`.
     */
    fun onQueueDrained(): Boolean {
        if (!isSpeechEnabled || !isTurnEnded) return false
        isSpeechEnabled = false
        return true
    }
}
