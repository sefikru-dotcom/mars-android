package ru.mars.mobile

/**
 * Тексты индикации потоковой озвучки: чем заменён голос и какие фразы не прозвучали.
 *
 * ## Зачем отдельная политика
 * Резерв и отказ — разрешённое поведение, МОЛЧАНИЕ о них — дефект. У потоковой озвучки два
 * события, о которых человек обязан узнать:
 * 1. облако отказало, фразу прочитала локальная модель ([LOCAL_FALLBACK]) — иначе человек,
 *    выбравший сетевой голос, слышит «не тот голос» без объяснения;
 * 2. фразу не удалось озвучить вовсе ([LOCAL_FAILED] / [phraseFailed]) — иначе посреди
 *    ответа просто исчезает кусок, и это неотличимо от «модель забыла сказать».
 *
 * Текст — тоже контракт: он должен совпадать с тем, что человек видит в неразрывной озвучке
 * ([VoiceSubstitutionNotice]), иначе один и тот же сбой описывается двумя разными фразами в
 * двух чатах. Поэтому текст подмены здесь не дублируется, а берётся из общего объекта.
 *
 * Класс чистый (никакого `android.*` и состояния), поэтому правила проверяются JVM-тестом.
 *
 * ## Что НЕ говорится
 * Ни кода ошибки, ни текста реплики: человеку нужно понять «почему тихо», а не читать `429`.
 * Причина остаётся аргументом ([phraseFailed]) и живёт в логах/диагностике.
 */
object StreamSpeechNotice {

    /**
     * Облако не дало звука, фразу читает локальная модель Piper.
     *
     * Тот же текст, что у неразрывной озвучки: подмена голоса — одно событие, и описываться
     * оно должно одинаково независимо от того, каким путём пошла реплика.
     */
    const val LOCAL_FALLBACK: String = VoiceSubstitutionNotice.CLOUD_FAILED

    /**
     * Ни облако, ни локальная модель не дали звука: фраза пропущена.
     *
     * Отдельный текст от [phraseFailed], потому что причина здесь не в конкретном коде
     * сервера, а в том, что резерв кончился: человеку важно знать, что дело не в сети.
     */
    const val LOCAL_FAILED: String =
        "Облачный и локальный голос недоступны — фраза не озвучена"

    /** Общий текст, когда причина неизвестна: тишина без объяснения недопустима. */
    const val PHRASE_SKIPPED: String = "Фразу не удалось озвучить"

    /**
     * Текст для пропущенной фразы по причине отказа очереди.
     *
     * Причины — те же строки, что отдают клиент синтеза и очередь
     * ([ru.mars.network.repository.ServerTtsResult.Unavailable.reason], `playback`), поэтому
     * незнакомая строка не оставляет человека без сообщения, а даёт общий текст.
     */
    fun phraseFailed(reason: String): String = when (reason.trim().lowercase()) {
        "rate_limited" -> "Сервер озвучки перегружен — фраза не озвучена"
        "unauthorized" -> "Сервер озвучки не принял авторизацию — фраза не озвучена"
        "not_found" -> "Голос не найден на сервере — фраза не озвучена"
        "server_error" -> "Сервер озвучки ответил ошибкой — фраза не озвучена"
        "transport" -> "Нет связи с сервером озвучки — фраза не озвучена"
        "empty_audio", "invalid_response" -> "Сервер вернул пустое аудио — фраза не озвучена"
        "playback", "playback_rejected" -> "Не удалось воспроизвести фразу"
        else -> PHRASE_SKIPPED
    }
}
