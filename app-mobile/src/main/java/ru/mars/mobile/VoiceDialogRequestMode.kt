package ru.mars.mobile

/**
 * Явный признак «этот ход начат голосовым диалогом» для тела `POST /api/chat/start`.
 *
 * Зачем поле, если режим и так виден по поведению: серверу нужно отличать голосовой ход от
 * набранного руками, чтобы выбрать голосовую политику ответа (краткость, отсутствие разметки,
 * допустимость промежуточных реплик). Выводить это из текста нельзя — одна и та же фраза
 * может быть набрана и сказана, а «угадывать по косвенным признакам» значит получить разное
 * поведение на одинаковых запросах.
 *
 * ## Имя поля: `voice_mode`, а не `voice_dialog`
 * Первоначальный UI-контракт называл поле `voice_dialog` — это ошибка контракта, а не сервера.
 * Фактический параметр серверного `POST /api/chat/start` — **`voice_mode: boolean`**
 * (см. `SERVER-CONTRACT.md` и разбор `api/chat.py`): любое другое имя сервер просто игнорирует,
 * и ход молча уходит как текстовый. Именно поэтому константа закреплена здесь и проверяется
 * тестом: опечатка в имени не даёт ошибки ни на клиенте, ни на сервере — только неверное
 * поведение, которое видно лишь по стилю ответа.
 *
 * Почему только константа и функция, а не сама отправка: тело запроса собирает
 * `ChatRepository` (зона Z3). UI-зона не правит чужой файл, поэтому здесь зафиксирован
 * контракт — имя поля и правило «не активен → поля нет» (отсутствие ключа оставляет серверу
 * его текущую политику, это backward-compatible payload).
 *
 * ## Требуемая серверная версия
 * Поле принимается сервером, но на проверенной ревизии (`f898bf46a`, ревью `PASSED FALSE`)
 * ветка runner-а для `voice_mode` — silent no-op: значение доходит до модели, но не меняет
 * голосовую политику. Клиент шлёт поле правильно; поведение включится на серверной версии с
 * исправленным runner-ом. Клиентская сторона это не обходит и поле не переименовывает.
 *
 * Обычный набор текста в композере этот признак не включает: поле описывает ИСТОЧНИК хода,
 * а не доступность интерфейса.
 */
object VoiceDialogRequestMode {

    /** Имя поля в JSON-теле запроса хода — как его читает сервер. */
    const val FIELD = "voice_mode"

    /** Устаревшее (ошибочное) имя из первой редакции UI-контракта. Только для диагностики. */
    const val LEGACY_WRONG_FIELD = "voice_dialog"

    /**
     * Значение поля: `true` для хода из голосового диалога, `null` — поля в теле не будет.
     *
     * `null`, а не `false`: явный `false` пришлось бы объяснять серверу («точно не голос»), а
     * это уже другая семантика — «пользователь отказался от голоса», которой не существует.
     */
    fun fieldValue(voiceDialog: Boolean): Boolean? = if (voiceDialog) true else null
}
