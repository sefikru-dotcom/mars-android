package ru.mars.mobile

/**
 * Что из хода вообще можно произносить вслух — и сколько раз.
 *
 * Ход присылает четыре разных вида текста, и раньше хост видел их одинаково:
 * - **сгенерированный ответ** (`ChatEvent.Chunk`) — это и есть ответ, его читаем;
 * - **размышления** (`ChatEvent.Thought`) — черновик модели, в нём есть предположения и
 *   самоопровержения. Озвучивать их значит читать вслух «сначала я подумал X, но нет, Y»:
 *   человек слышит не ответ, а кухню. Не произносим НИКОГДА;
 * - **прогресс** (`ChatEvent.Phase`, статусы инструментов) — служебные имена фаз
 *   (`planning`, `tool_call`), в речи они звучат как отладка. Для голоса есть одна честная
 *   фраза-признание, что работа идёт, — [PROGRESS_LINE], и только она;
 * - **инструменты** (`ChatEvent.ToolCall`/`ToolResult`) — вызов и результат. Результат
 *   произносить нельзя: он технический (JSON, пути, коды) и, главное, это НЕ ответ — человек
 *   услышал бы сырые данные, а потом ещё раз то же самое в пересказе модели.
 *
 * Отсюда правила, которые проверяет `VoiceTurnSpeechPolicyTest`:
 * - [onToolStarted] отдаёт [PROGRESS_LINE] ОДИН раз за ход, сколько бы инструментов ни
 *   вызвалось: пять подряд идущих вызовов — это одна фраза «Проверяю…», а не пять. Фраза
 *   ничего не обещает про результат («проверяю», не «нашёл»), поэтому не бывает выдуманной;
 * - [onToolStarted] молчит, если ответ уже начал звучать: вклинивать «Проверяю…» в середину
 *   читаемого предложения — худший способ сообщить о работе;
 * - [onToolFinished] и [onProgress] молчат всегда (возвращают `null`);
 * - [onDeliberation] молчит всегда и НЕ считается «уже что-то сказали»: размышления не должны
 *   ни блокировать «Проверяю…», ни отменять чтение финального ответа;
 * - [onFinal] отдаёт финальный текст только если в этом ходу ещё ничего не звучало: после
 *   потоковой озвучки терминальный `Done` не должен читать ответ второй раз.
 *
 * Класс чистый: ни Android, ни движка, ни сети — только текст на входе и решение на выходе.
 * Хост ([ChatActivity]) зовёт его из конвейера событий и передаёт результат в озвучку.
 */
class VoiceTurnSpeechPolicy {

    /** В этом ходу уже звучал сгенерированный ответ (дельты стрима). */
    var generatedSpoken: Boolean = false
        private set

    /** Фраза «работаю» уже произнесена в этом ходу. */
    var progressAnnounced: Boolean = false
        private set

    /** Новый ход: счётчики обнуляются, следующий ответ снова читается с чистого листа. */
    fun onTurnStarted() {
        generatedSpoken = false
        progressAnnounced = false
    }

    /**
     * Дельта сгенерированного ответа. Возвращает её же — фильтрация разметки и границ фраз
     * живёт в [StreamingSpeechController], а не здесь. Пустая дельта — `null`.
     */
    fun onGeneratedText(delta: String): String? {
        if (delta.isEmpty()) return null
        generatedSpoken = true
        return delta
    }

    /** Размышления модели: не произносятся никогда и не считаются сказанным. */
    fun onDeliberation(text: String): String? = null

    /**
     * Инструмент начал работу. Одна фраза [PROGRESS_LINE] на ход, и только пока ответ молчит:
     * человек слышит, что Марс занят, но не получает ни обещанного, ни выдуманного результата.
     */
    fun onToolStarted(name: String): String? {
        if (generatedSpoken || progressAnnounced) return null
        progressAnnounced = true
        return PROGRESS_LINE
    }

    /** Инструмент закончил: результат технический и НЕ ответ — не произносим. */
    fun onToolFinished(name: String): String? = null

    /** Служебная фаза хода: остаётся в статусной строке, в речь не попадает. */
    fun onProgress(phase: String): String? = null

    /**
     * Терминальный финал хода. `null` — ответ уже звучал потоково, повторять нельзя; иначе —
     * текст для разового чтения (ход без стрима: восстановление, фолбэк).
     */
    fun onFinal(text: String?): String? {
        val answer = text?.trim().orEmpty()
        if (answer.isEmpty()) return null
        if (generatedSpoken) return null
        generatedSpoken = true
        return answer
    }

    companion object {
        /**
         * Единственная голосовая фраза прогресса. Настоящее время, без результата и без
         * оценки: «Проверяю…» верно и когда инструмент найдёт данные, и когда упадёт.
         */
        const val PROGRESS_LINE = "Проверяю…"
    }
}
