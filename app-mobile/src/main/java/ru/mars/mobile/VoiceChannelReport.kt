package ru.mars.mobile

/**
 * Каким каналом РЕАЛЬНО прозвучала реплика.
 *
 * Зачем отдельный тип, а не строка: владелец слышит «не тот голос», но по логу не отличить,
 * ушёл ли звук провайдеру PlusVibe напрямую, на сервер Марса, в Piper или в системный синтез.
 * Значения идут в порядке деградации — от самого качественного канала к немому, поэтому
 * по одному имени канала в строке лога видно, насколько глубоко провалилась цепочка.
 */
internal enum class VoiceOutcomeChannel {
    CLOUD_PAID,
    CLOUD_SERVER,
    OFFLINE_PIPER,
    SYSTEM_TTS,
    NONE,
}

/**
 * Факт одной реплики: что выбрали, чем прозвучало, почему не выбранным.
 * Без текста реплики и без ключей.
 *
 * [atMs] — момент, к которому относится реплика (epoch ms). Нужен, потому что в одном
 * разговоре реплик много, а `adb logcat` отдаёт их подряд: без времени нельзя понять,
 * какая строка относится к тому ответу, на который жаловался владелец.
 */
internal data class VoiceReport(
    val wantedProfileId: String?,
    val actualChannel: VoiceOutcomeChannel,
    val actualProfileId: String?,
    val reason: String?,
    val atMs: Long,
) {
    /**
     * Прозвучало ли ровно то, что человек выбрал.
     *
     * `reason != null` — деградация зафиксирована явно, и спорить не о чем: даже если профиль
     * в итоге совпал, звук пришёл другим путём (резервный синтез тем же id звучит иначе).
     * Смена профиля без причины — тоже подмена: ровно этот случай владелец описывает как
     * «меняется визуально, а по факту нет». Совпадение профиля без причины — единственный
     * случай, когда подмены не было.
     */
    val substituted: Boolean
        get() = reason != null || (wantedProfileId != null && actualProfileId != wantedProfileId)
}
