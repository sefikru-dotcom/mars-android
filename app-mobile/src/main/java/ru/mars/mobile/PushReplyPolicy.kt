package ru.mars.mobile

/**
 * Политика «ответить прямо из push-уведомления»: когда кнопка ответа вообще законна,
 * что считать отправляемым текстом и что сказать человеку, если отправка не удалась.
 *
 * Ни одного импорта `android.*`: решение о кнопке, нормализация текста и текст отказа —
 * это данные и работа со строкой, а не разметка. Поэтому всё проверяется JVM-тестом
 * (`PushReplyPolicyTest`) без эмулятора, а framework-клей остаётся тонким:
 * `fcm/PushNotifications` собирает действие и `PendingIntent`, `ChatActivity.onNewIntent`
 * забирает текст из `RemoteInput` и отдаёт его композитору.
 *
 * Почему ключи живут здесь, а не в `PushNotifications`. Extras ответа пишет один файл
 * (уведомление), читает другой (экран), а третий — вход в приложение после смерти
 * процесса. Три копии строковых литералов в трёх файлах гарантированно разъедутся
 * молча: уведомление «отправит», а экран не найдёт текст и покажет пустой композитор.
 * Один объект — одна правда о том, как называется каждое поле.
 *
 * Почему действие объявлено здесь, а не как константа интента: значение действия —
 * часть контракта между уведомлением и экраном (сравнение `intent.action`), а не
 * деталь одного из них. Пока оно в политике, проверка «это наш интент» тестируема.
 */
object PushReplyPolicy {

    /**
     * Любая последовательность пробельных символов — то, что сжимается в один пробел.
     *
     * Объявлена первой намеренно: свойства объекта инициализируются в порядке
     * объявления, и если этот шаблон позже понадобится в инициализаторе другого
     * свойства, он обязан быть готовым к тому моменту.
     */
    private val WHITESPACE_RUN = Regex("\\s+")

    /**
     * Действие интента «ответ из шторки».
     *
     * Значение с префиксом пакета намеренно: действие приходит из системного
     * `PendingIntent`, и случайное совпадение с чужим `Intent.ACTION_*` должно быть
     * невозможно. Суффикс — не `ru.mars.mobile.REPLY`, потому что «ответ» в проекте
     * уже означает ответ модели на ход, а здесь речь именно о push.
     */
    const val ACTION_REPLY: String = "ru.mars.mobile.PUSH_REPLY"

    /**
     * Extra интента: сессия, в которую уйдёт ответ.
     *
     * Имя не совпадает с [ChatActivity.EXTRA_OPEN_SESSION_ID] (`extra_open_session_id`)
     * специально. Это разные вещи: открытие диалога — навигация, ответ — отправка в
     * конкретный диалог, и значение второго нельзя «переиспользовать» как навигацию.
     * Если бы ключи совпали, `onNewIntent` открыл бы диалог и промолчал о тексте.
     *
     * Префикс `push_` (а не `extra_`) держит контракт с data-payload сервера, где
     * ключ сессии — `session_id`: значение переносится как есть, без переименования
     * смысла. Исходную пару «payload → уведомление» разбирает
     * `PushMessagePolicy`/`PushNotificationSpec.sessionId`.
     */
    const val EXTRA_SESSION_ID: String = "push_session_id"

    /**
     * Extra интента: текст, который человек набрал в `RemoteInput`.
     *
     * Кладётся рядом с [EXTRA_SESSION_ID], а не вместо него: `RemoteInput` доставляет
     * текст в `Bundle` результатов, и экран достаёт его оттуда. Для маршрутов, где
     * `RemoteInput` недоступен (старый API, повторный показ уведомления), этот extra
     * остаётся резервным источником того же значения.
     */
    const val EXTRA_TEXT: String = "push_reply_text"

    /**
     * Ключ `RemoteInput`: имя поля ввода внутри уведомления.
     *
     * Должно быть стабильным между показом уведомления и чтением результата — система
     * сопоставляет результат именно по нему. Поэтому константа, а не литерал в двух
     * местах.
     */
    const val KEY_TEXT: String = "push_reply_input"

    /**
     * Extra интента: id уведомления, из которого пришёл ответ.
     *
     * Нужен, чтобы погасить шторку после ответа. `setAutoCancel(true)` срабатывает
     * только на тап по телу уведомления, а не на нажатие действия: без этого ключа
     * ответ уходит, а уведомление остаётся висеть с уже устаревшим текстом события.
     * `cancelAll()` здесь недопустим — он снёс бы и другие уведомления Марса, к
     * которым человек ещё не притронулся.
     */
    const val EXTRA_NOTIFICATION_ID: String = "push_notification_id"

    /** Подпись действия в шторке: кнопка, открывающая поле ввода. */
    const val LABEL_REPLY: String = "Ответить"

    /** Подпись кнопки отправки внутри поля ввода. */
    const val LABEL_SEND: String = "Отправить"

    /** Подсказка (hint) поля ввода: короткая, иначе обрезается в шторке. */
    const val HINT: String = "Сообщение"

    /**
     * Текст отказа по умолчанию — когда сервер промолчал или прислал пустоту.
     *
     * Формулировка в стиле проекта (`MusicAlbumPolicy.NETWORK_FAILURE`,
     * `MemoryTabPolicy.DEFAULT_FAILURE`): «Не удалось …» + подсказка, что делать.
     * Голое «Ошибка» человеку ничего не говорит: он уже видел, что что-то не так —
     * ему нужен следующий шаг.
     */
    const val FAILURE_DEFAULT: String = "Не удалось отправить ответ — проверьте сеть"

    /**
     * Показывать ли действие ответа для этой сессии.
     *
     * Три условия, и все три — про то, что сервер реально примет ответ:
     *
     * 1. [sessionId] не пустой. Без адресата ответ уходит «в никуда»: уведомление без
     *    `session_id` (и без deep-link) не привязано к диалогу, и отправлять из него
     *    некуда. Пустая строка и `null` — одно и то же: сервер кладёт ключ только
     *    когда сессия есть.
     * 2. Не [readOnly]. В диалоге «только для чтения» композитор заблокирован на
     *    клиенте (`ChatActivity.sendMessage` → «Сессия доступна только для чтения»),
     *    и сервер отклонит ход. Кнопка, которая гарантированно ведёт к отказу, хуже
     *    отсутствия кнопки: человек тратит набор текста впустую.
     * 3. Не [subagent]. Субагентские диалоги — view-only (A13): операции над ходом
     *    запрещены сервером, ответ в них не пройдёт по той же причине, что и readOnly.
     *
     * Почему не наоборот («показать всегда, а ошибку покажем потом»): шторка — это
     * место, где человек действует одной рукой и не читает пояснений. Действие,
     * ведущее к отказу, там дороже, чем его отсутствие.
     */
    fun canReply(sessionId: String?, readOnly: Boolean, subagent: Boolean): Boolean {
        if (readOnly || subagent) return false
        return !sessionId.isNullOrBlank()
    }

    /**
     * Текст из уведомления: нормализация и защита от пустого.
     *
     * Что делает и почему именно это:
     * - срезает края — `RemoteInput` часто отдаёт строку с хвостовым переводом строки,
     *   и он попал бы в сообщение как пустая строка в конце;
     * - сжимает повторные пробелы **внутри** (включая переводы строк) в один пробел.
     *   Набранное в однострочном поле шторки — всегда одна реплика; многострочность
     *   здесь означает случайный перенос из буфера обмена, а не замысел. Плюс сервер
     *   видит тот же текст, что и человек в поле ввода;
     * - пустое и пробельное — `null`, а не `""`. Разница принципиальна: `null` — это
     *   «отправлять нечего», и вызывающий молча закрывает уведомление, не создавая
     *   пустой ход. Пустая строка в этом месте означала бы «отправить пустое
     *   сообщение», и решение пришлось бы принимать каждому вызывающему отдельно.
     *
     * Длину не ограничивает: обрезать чужой текст молча — худший из вариантов, а
     * предел поля ввода задаёт `RemoteInput` на стороне уведомления.
     */
    fun normalizeReply(raw: String?): String? {
        val collapsed = raw?.replace(WHITESPACE_RUN, " ")?.trim().orEmpty()
        return collapsed.takeIf { it.isNotEmpty() }
    }

    /**
     * Что показать, если ответ отправить не удалось.
     *
     * [error] — текст отказа сервера или исключения (может быть `null`, пустым или
     * пробельным). Причина добавляется к своей формулировке, а не заменяет её: сервер
     * иногда отвечает технической строкой («HTTP 502»), и без «Не удалось отправить
     * ответ» человек не поймёт, о каком действии речь.
     *
     * Пустая причина не даёт висящего двоеточия — вместо неё [FAILURE_DEFAULT].
     */
    fun failureNotice(error: String?): String {
        val reason = error?.replace(WHITESPACE_RUN, " ")?.trim().orEmpty()
        if (reason.isEmpty()) return FAILURE_DEFAULT
        return "Не удалось отправить ответ: $reason"
    }

    /**
     * Наш ли это интент ответа.
     *
     * Помощник для диспетчеризации в `onNewIntent`: экран получает и тапы по
     * уведомлению (там действия нет), и ответы (там есть), и сравнивать строку
     * действия вручную в каждом месте — источник опечаток. `null` и пустое действие
     * дают `false`: обычный тап ответом не является.
     */
    fun matchesAction(action: String?): Boolean = action == ACTION_REPLY
}
