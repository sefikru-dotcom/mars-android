package ru.mars.mobile

/**
 * План правки своей реплики: что останется, что уйдёт и что уйдёт вместо этого.
 *
 * Зачем отдельный тип, а не три числа рядом: экран показывает человеку последствия ДО
 * нажатия («Будет удалено 4 сообщения»), а презентер по тем же числам режет историю.
 * Если бы каждый считал их сам, лист правки и реальная обрезка могли разойтись на
 * единицу — и человек терял бы не то, что ему обещали.
 *
 * [messageId] — строка, которую правят: по нему презентер находит её в ленте, чтобы
 * отрезать хвост ровно перед ней.
 *
 * [keepBefore] — сколько строк остаётся ДО правленой реплики (её индекс). Сама реплика
 * в остаток не входит: она заменяется новым текстом, а не соседствует с ним.
 *
 * [dropAfter] — сколько строк уходит ПОСЛЕ неё. Ноль означает, что правят последнюю
 * реплику: удалять нечего, но ответ на неё всё равно надо перезапросить — он отвечал на
 * прежний текст.
 */
data class LocalChatEditPlan(
    val messageId: String,
    val newText: String,
    val keepBefore: Int,
    val dropAfter: Int,
) {
    /**
     * Текст не годится к отправке.
     *
     * Свойство оставлено по контракту волны, но через [LocalChatEditPolicy.plan] пустой
     * текст до плана не доходит — там он отсекается раньше и даёт `null`. Значение имеет
     * для планов, собранных руками (тест, будущий вызывающий), чтобы «пустой» нельзя было
     * принять за нормальную правку.
     */
    val isNoop: Boolean get() = newText.isBlank()
}

/**
 * Правила инлайн-правки своей реплики в локальном диалоге.
 *
 * Зачем отдельный файл, а не проверки в обработчике долгого нажатия: правка режет
 * историю, то есть это единственное действие над лентой, которое уносит с собой чужие
 * сообщения. Ошибка здесь стоит не «неудобно», а «человек потерял диалог». Поэтому
 * правила — чистая функция без `android.*`: их видно в тесте целиком
 * (`LocalChatEditPolicyTest`), а экран остаётся тонким и только рисует то, что решила
 * политика.
 *
 * Что политика НЕ делает: не трогает ленту, не ходит в сеть, не собирает текст запроса.
 * Она отвечает на три вопроса: «можно ли править эту строку», «что именно уйдёт» и
 * «как объяснить это человеку одной строкой».
 *
 * Стрим запрещает правку целиком. Причина не в осторожности: пока идёт ответ, лента
 * дописывается кадрами, и обрезка по индексу, снятому в момент открытия листа, попала бы
 * в середину чужого хода — модель получила бы историю без половины ответа, на который
 * сама же ссылается.
 */
object LocalChatEditPolicy {

    /** Заголовок диалога правки. */
    const val TITLE: String = "Изменить сообщение"

    /** Подсказка, когда правят последнюю реплику: удалять нечего, ответ перезапросят. */
    const val REGENERATE_HINT: String = "Ответ будет перезапрошен"

    /** Начало подсказки об удалении: к нему приклеивается число и слово «сообщение». */
    const val DROP_PREFIX: String = "Будет удалено"

    /**
     * Попытка отправить пустую реплику.
     *
     * Почему не «просто не отправлять»: человек нажал кнопку, и молчание читалось бы как
     * зависание. Диалог такую попытку отклонит сам (кнопка неактивна), но текст может
     * стать пустым уже после нажатия — тогда это единственный след.
     */
    const val EMPTY_HINT: String = "Реплика пустая — отправлять нечего"

    /**
     * Можно ли править строку.
     *
     * [streaming] — идёт ход (презентер в состоянии стрима), а не «эта строка стримится».
     * Разделение важное: у реплики человека флаг стрима не поднимается никогда, но именно
     * во время чужого стрима править нельзя (см. KDoc класса).
     *
     * Роль, инструмент и непустой текст проверяет [LocalChatActions.canEdit] — то же
     * правило, по которому пункт «Изменить» попадает в список действий. Делегирование, а
     * не копия условий: иначе лист однажды предложил бы пункт, который политика потом
     * отклонит, и нажатие молча ничего бы не делало.
     */
    fun canEdit(item: LocalChatItem, streaming: Boolean): Boolean =
        !streaming && LocalChatActions.canEdit(item)

    /**
     * План правки или `null`, если править нечего.
     *
     * `null` возвращается в трёх случаях, и все три — «действие невозможно», а не «пока не
     * готово»:
     * - строки с таким [messageId] в ленте нет (её успели срезать/перерисовать);
     * - строка не своя реплика (ответ ассистента, карточка инструмента) — правка чужого
     *   текста унесла бы с собой ответы, к которым он отношения не имеет;
     * - текст пуст или состоит из пробелов: отправлять нечего, а стереть свою реплику
     *   правкой нельзя — для этого есть удаление.
     *
     * Текст обрезается по краям: с клавиатуры почти всегда приезжает лишний перевод
     * строки, а он ушёл бы провайдеру как часть реплики и в истории выглядел бы как
     * пустая строка в конце пузыря.
     */
    fun plan(items: List<LocalChatItem>, messageId: String, newText: String): LocalChatEditPlan? {
        val index = items.indexOfFirst { it.id == messageId }
        if (index < 0) return null
        // Состояние хода (глобальный стрим) здесь не проверяется: у плана нет доступа к
        // презентеру. Экран спрашивает [canEdit] ДО открытия листа, то есть до того, как
        // план понадобится, а собственный флаг строки [LocalChatActions.canEdit] проверяет
        // сам — стримящаяся строка плана не получит.
        if (!canEdit(items[index], streaming = false)) return null
        if (!canApply(newText)) return null
        return LocalChatEditPlan(
            messageId = messageId,
            newText = normalize(newText),
            keepBefore = index,
            dropAfter = items.size - index - 1,
        )
    }

    /**
     * Подсказка под полем: что произойдёт после «Отправить заново».
     *
     * Два разных исхода, и человек обязан видеть разницу: правка середины стирает всё, что
     * было сказано после (включая ответы ассистента), а правка последней реплики ничего не
     * стирает — просто ответ будет другим.
     *
     * Слово «сообщение» согласуется с числом: «удалено 1 сообщение», «удалено 3 сообщения»,
     * «удалено 5 сообщений». Формулировка из контракта волны («Будет удалено N сообщений»)
     * давала «удалено 2 сообщений» — по-русски это ошибка, и живой человек прочитал бы её
     * как небрежность приложения, а не как точное число.
     */
    fun hint(plan: LocalChatEditPlan): String =
        if (plan.dropAfter <= 0) {
            REGENERATE_HINT
        } else {
            "$DROP_PREFIX ${plan.dropAfter} ${messagesWord(plan.dropAfter)}"
        }

    /**
     * Годится ли текст к отправке.
     *
     * Один источник истины для двух мест: кнопка «Отправить заново» гаснет ровно тогда,
     * когда [plan] вернул бы `null`. Иначе получилась бы либо живая кнопка с мёртвым
     * нажатием, либо погасшая там, где план строится.
     */
    fun canApply(text: String): Boolean = normalize(text).isNotEmpty()

    /** Текст в том виде, в каком он уйдёт в историю: без пробелов по краям. */
    fun normalize(text: String): String = text.trim()

    /** Русское слово для числа сообщений (1 сообщение, 2 сообщения, 5 сообщений). */
    private fun messagesWord(count: Int): String {
        val mod100 = count % 100
        val mod10 = count % 10
        return when {
            // 11..14 — исключение: «11 сообщение» по-русски не бывает.
            mod100 in 11..14 -> "сообщений"
            mod10 == 1 -> "сообщение"
            mod10 in 2..4 -> "сообщения"
            else -> "сообщений"
        }
    }
}